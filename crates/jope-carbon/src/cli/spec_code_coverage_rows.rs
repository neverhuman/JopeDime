/// Resolve `(anchor_start, anchor_end)` to 1-based inclusive `(start_line, end_line)` in `file`.
pub fn resolve_anchor_span(
    file: &str,
    anchor_start: &str,
    anchor_end: &str,
) -> Result<(usize, usize), String> {
    let src = embedded_source_for_file(file)?;
    let lines: Vec<&str> = src.lines().collect();
    if lines.is_empty() {
        return Err(format!("empty embedded source for {file}"));
    }
    let start_idx = lines
        .iter()
        .position(|l| l.contains(anchor_start))
        .ok_or_else(|| format!("anchor_start '{anchor_start}' not found in {file}"))?;
    let end_line = if anchor_end == "__EOF__" {
        lines.len()
    } else {
        let rel = lines[start_idx + 1..]
            .iter()
            .position(|l| l.contains(anchor_end))
            .ok_or_else(|| {
                format!(
                    "anchor_end '{anchor_end}' not found after L{} in {file}",
                    start_idx + 1
                )
            })?;
        (start_idx + 1 + rel).max(start_idx + 1)
    };
    Ok((start_idx + 1, end_line))
}

