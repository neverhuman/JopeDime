//! Historical GPU-study staging and the corrected fitting-only staging
//! protocol (W1-T07).
//!
//! The admitted v2 GPU study of 2026-09-25 staged its inputs with a planner
//! that parsed every development target — including the cut-0 outer scoring
//! labels — before projecting the fitting rows; the run then failed before
//! CUDA qualification. That history is recorded, never rewritten:
//!
//! * [`HistoricalDisposition`] binds the retained evidence by digest and
//!   records only what that evidence states: the observed access, the actual
//!   execution extent, the objects derived through the flawed staging path
//!   ("affected descendants") and the unknowns. It infers no contamination,
//!   marks the run as not protocol-compliant and not a qualified measurement,
//!   and excludes it from headline measurements. It is derived from the
//!   custody files by [`derive_disposition`], which cross-checks them.
//! * [`CorrectedProtocol`] is a new identity for fitting-only staging, a pure
//!   function of the disposition ([`CorrectedProtocol::derive`]). It forbids
//!   the historical projection source, every object of the historical input
//!   closure and the historical execution window.
//! * [`verify_closure`] and [`verify_corrected_run`] are the replay verifier:
//!   the historical input closure (or any object of it) is rejected for the
//!   corrected protocol, and a corrected run is accepted only with its own
//!   identity, its own window and a fitting-only projection declaration.
//!
//! The three documents use canonical JSON (see
//! [`crate::regression_release::canonical_json`]), exact schemas, no unknown
//! fields and a content identity, so one can never be opened as another and
//! no field can change without changing the identity.
//!
//! [`committed`] opens the committed release pair embedded at build time; the
//! jope-bench planner and plan admission use it with [`verify_closure`] and
//! [`refuse_historical_objects`] (W1 follow-up 2d).
//!
//! Limits: a producer's projection attestation is recorded and required, not
//! independently proven. The closure check is by digest: it authenticates
//! bytes, so a re-encoded copy of a historical projection is a new object.

