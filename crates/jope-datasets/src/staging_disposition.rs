impl HistoricalDisposition {
    pub fn open(bytes: &[u8]) -> Result<Self> {
        let d: Self = open_document(bytes, DISPOSITION_SCHEMA, "historical staging disposition")?;
        d.validate()?;
        Ok(d)
    }

    pub fn encode(&self) -> Result<Vec<u8>> {
        canonical(self)
    }

    pub fn compute_id(&self) -> Result<String> {
        identity(self, "disposition_id")
    }

    pub fn validate(&self) -> Result<()> {
        ensure!(
            self.schema == DISPOSITION_SCHEMA,
            "unsupported disposition schema"
        );
        let s = &self.study;
        ensure!(
            is_git_sha(&s.source_sha)
                && is_sha256(&s.binary_sha256)
                && is_sha256(&s.plan_sha256)
                && is_sha256(&s.window_experiment_sha256)
                && s.plan_schema == HISTORICAL_PLAN_SCHEMA
                && s.window_deadline_unix_ms > s.window_started_unix_ms,
            "historical study identity malformed"
        );
        let c = &self.input_closure;
        ensure!(
            c.manifest_schema == FITTING_INPUTS_SCHEMA
                && is_sha256(&c.manifest_sha256)
                && c.projection_source_sha == s.source_sha
                && is_sha256(&c.panel_sha256)
                && is_sha256(&c.configuration_sha256)
                && !c.members.is_empty(),
            "historical input closure malformed or not produced by the study source"
        );
        for m in &c.members {
            ensure!(
                !m.dataset.is_empty()
                    && is_sha256(&m.raw_sha256)
                    && is_sha256(&m.assignment_sha256)
                    && m.gp_fold_sha256.iter().all(|f| is_sha256(f)),
                "historical closure member {} malformed",
                m.dataset
            );
        }
        let o = &self.observed;
        let k = &self.classification;
        // Only what the evidence states is recorded; nothing is upgraded.
        ensure!(
            !k.contamination_inferred
                && !k.original_result_reclassified
                && k.excluded_from_headline
                && (!o.outer_scoring_labels_parsed || !k.protocol_compliant)
                && (o.gpu_qualification_executed || !k.qualified_measurement),
            "a historical disposition may not infer contamination, reclassify the result, \
             claim compliance after a recorded deviation or qualify an unqualified run"
        );
        ensure!(
            !self.unknowns.is_empty()
                && !self.execution_extent.is_empty()
                && !self.affected_descendants.is_empty()
                && !self.evidence.is_empty(),
            "a historical disposition records its extent, descendants, unknowns and evidence"
        );
        for d in &self.affected_descendants {
            ensure!(
                is_sha256(&d.sha256),
                "descendant {} digest malformed",
                d.kind
            );
        }
        for e in &self.evidence {
            ensure!(
                matches!(e.location.as_str(), "repository" | "custody") && is_sha256(&e.sha256),
                "evidence {} malformed",
                e.path
            );
        }
        ensure!(
            self.disposition_id == self.compute_id()?,
            "disposition identity does not match its content"
        );
        Ok(())
    }

    /// Objects produced by the historical staging path: the fitting-input
    /// manifest, every projected fitting input and every inner-fold input.
    /// Label-free frozen split memberships are panel inputs, not products.
    pub fn staging_products(&self) -> BTreeSet<String> {
        let c = &self.input_closure;
        let mut products = BTreeSet::from([c.manifest_sha256.clone()]);
        for m in &c.members {
            products.insert(m.raw_sha256.clone());
            products.extend(m.gp_fold_sha256.iter().cloned());
        }
        products
    }
}

