fn components(path: &str) -> Vec<&str> {
    path.split('/').collect()
}

fn read(root: &Path, path: &str) -> Result<Vec<u8>> {
    read_exact_object(root, &components(path))
}

fn parse(bytes: &[u8], what: &str) -> Result<Value> {
    serde_json::from_slice(bytes).with_context(|| format!("parse {what}"))
}

fn text<'a>(value: &'a Value, key: &str, what: &str) -> Result<&'a str> {
    value[key]
        .as_str()
        .with_context(|| format!("{what}: {key} absent"))
}

fn flag(value: &Value, key: &str, what: &str) -> Result<bool> {
    value[key]
        .as_bool()
        .with_context(|| format!("{what}: {key} absent"))
}

fn count(value: &Value, key: &str, what: &str) -> Result<u64> {
    value[key]
        .as_u64()
        .with_context(|| format!("{what}: {key} absent"))
}

/// Derive the disposition from the retained custody files of the study
/// (`study_root`) and the repository evidence documents (`repository_root`).
/// Every file is read as an exact regular object (no symlink, no fallback);
/// the documents are cross-checked for one source, one window and one set of
/// recorded outcomes before anything is recorded.
pub fn derive_disposition(
    study_root: &Path,
    repository_root: &Path,
) -> Result<HistoricalDisposition> {
    let mut evidence = Vec::new();
    let mut custody = |path: &str, role: &str| -> Result<Vec<u8>> {
        let bytes = read(study_root, path)?;
        evidence.push(EvidenceFile {
            location: "custody".into(),
            path: study_root.join(path).display().to_string(),
            sha256: sha256_hex(&bytes),
            role: role.into(),
        });
        Ok(bytes)
    };
    let manifest_bytes = custody(
        CUSTODY_FILES[0],
        "retained historical fitting-input manifest",
    )?;
    let plan_bytes = custody(CUSTODY_FILES[1], "historical v2 plan")?;
    custody(CUSTODY_FILES[2], "plan command")?;
    let deviation = parse(
        &custody(CUSTODY_FILES[3], "protocol deviation record")?,
        "deviation",
    )?;
    let closeout = parse(&custody(CUSTODY_FILES[4], "study closeout")?, "closeout")?;
    let stderr_sha = sha256_hex(&custody(CUSTODY_FILES[5], "controller stderr")?);
    let window = parse(&custody(CUSTODY_FILES[6], "admitted window")?, "window")?;
    let launch = parse(&custody(CUSTODY_FILES[7], "launch outcome")?, "launch")?;
    let binary_sha = sha256_hex(&custody(CUSTODY_FILES[8], "study binary")?);
    let manifest = parse(&manifest_bytes, "fitting-input manifest")?;
    let plan = parse(&plan_bytes, "plan")?;
    let mut repository = Vec::new();
    for path in REPOSITORY_FILES {
        let bytes = read(repository_root, path)?;
        evidence.push(EvidenceFile {
            location: "repository".into(),
            path: path.into(),
            sha256: sha256_hex(&bytes),
            role: "published evidence".into(),
        });
        repository.push(bytes);
    }
    let repo_deviation = parse(&repository[0], "repository deviation")?;
    let repo_closeout = parse(&repository[1], "repository closeout")?;
    let study_manifest = parse(&repository[2], "study manifest")?;
    let planner_proof = parse(&repository[4], "planner local proof")?;

    // One source, one window, one outcome across every document.
    let source = text(&deviation, "source_sha", "deviation")?.to_owned();
    ensure!(
        [
            text(&closeout, "source_sha", "closeout")?,
            text(&manifest, "projection_source_sha", "manifest")?,
            text(&study_manifest, "source_sha", "study manifest")?,
            text(&repo_deviation, "source_sha", "repository deviation")?,
        ]
        .iter()
        .all(|s| *s == source),
        "retained evidence names more than one staging source"
    );
    ensure!(
        repo_deviation == deviation && repo_closeout == closeout,
        "published and custody deviation/closeout records differ"
    );
    ensure!(
        closeout["window"] == window && launch["original_window"] == window,
        "retained evidence names more than one execution window"
    );
    ensure!(
        study_manifest["binary"]["sha256"] == binary_sha.as_str()
            && study_manifest["plan"]["sha256"] == sha256_hex(&plan_bytes).as_str(),
        "study binary or plan differs from the study manifest"
    );
    let files = closeout["files"]
        .as_object()
        .context("closeout files absent")?;
    for (suffix, digest) in [
        ("/plan.json", sha256_hex(&plan_bytes)),
        ("/run.stderr", stderr_sha.clone()),
    ] {
        let recorded = files
            .iter()
            .find(|(path, _)| path.ends_with(suffix))
            .with_context(|| format!("closeout does not bind {suffix}"))?;
        ensure!(
            recorded.1 == digest.as_str(),
            "closeout digest of {suffix} differs from the retained bytes"
        );
    }
    ensure!(
        text(&plan, "schema", "plan")? == HISTORICAL_PLAN_SCHEMA,
        "the retained plan is not the historical v2 plan"
    );

    // The historical input closure, re-verified against the retained objects.
    ensure!(
        text(&manifest, "schema", "manifest")? == FITTING_INPUTS_SCHEMA,
        "retained manifest is not a fitting-input manifest"
    );
    let assignments = manifest["assignments"]
        .as_object()
        .context("manifest assignments absent")?;
    let mut members = Vec::new();
    for input in manifest["inputs"]
        .as_array()
        .context("manifest inputs absent")?
    {
        let id = text(input, "id", "manifest input")?.to_owned();
        let retained = |artifact: &Value| -> Result<String> {
            let path = Path::new(text(artifact, "path", "artifact")?);
            let name = path
                .file_name()
                .and_then(|n| n.to_str())
                .context("artifact name")?;
            let digest = sha256_hex(&read(study_root, name)?);
            ensure!(
                artifact["sha256"] == digest.as_str(),
                "retained object {name} differs from the manifest"
            );
            Ok(digest)
        };
        let raw_sha256 = retained(&input["raw"])?;
        let mut gp_fold_sha256 = Vec::new();
        if let Some(folds) = input["gp"]["folds"].as_array() {
            for fold in folds {
                gp_fold_sha256.push(retained(&fold[0])?);
            }
        }
        members.push(ClosureMember {
            assignment_sha256: text(
                assignments.get(&id).context("assignment absent")?,
                "sha256",
                "assignment",
            )?
            .to_owned(),
            dataset: id,
            raw_sha256,
            gp_fold_sha256,
        });
    }
    let manifest_sha256 = sha256_hex(&manifest_bytes);
    let closure = Closure {
        manifest_schema: FITTING_INPUTS_SCHEMA.into(),
        manifest_sha256: manifest_sha256.clone(),
        projection_source_sha: source.clone(),
        panel_sha256: text(&manifest, "panel_sha256", "manifest")?.to_owned(),
        configuration_sha256: text(&manifest, "configuration_sha256", "manifest")?.to_owned(),
        members,
    };
    let observed = Observed {
        finding: text(&deviation, "finding", "deviation")?.to_owned(),
        outer_scoring_labels_parsed: flag(&deviation, "outer_scoring_labels_parsed", "deviation")?,
        sealed_target_tables_opened: flag(&deviation, "sealed_target_tables_opened", "deviation")?,
        outer_scoring_executed: flag(&deviation, "outer_scoring_executed", "deviation")?,
        campaign_held_looks_consumed: flag(
            &deviation,
            "campaign_held_looks_consumed",
            "deviation",
        )?,
        worker_payload_contains_outer_targets: flag(
            &deviation,
            "worker_payload_contains_outer_targets",
            "deviation",
        )?,
        gpu_qualification_executed: flag(&closeout, "gpu_qualification_executed", "closeout")?,
        direct_requests: count(&closeout, "direct_requests", "closeout")?,
        full_gp_arms: count(&closeout, "full_gp_arms", "closeout")?,
        prediction_batches: count(&closeout, "prediction_batches", "closeout")?,
        controller_exit_code: launch["exit_code"].as_i64().context("launch exit code")?,
        status: text(&closeout, "status", "closeout")?.to_owned(),
        failure: text(&closeout, "failure", "closeout")?.to_owned(),
    };
    ensure!(
        !flag(&deviation, "original_result_reclassified", "deviation")?,
        "the deviation record reclassified the original result"
    );
    let study = Study {
        stage: text(&deviation, "stage", "deviation")?.to_owned(),
        source_sha: source,
        binary_sha256: binary_sha,
        plan_schema: HISTORICAL_PLAN_SCHEMA.into(),
        plan_sha256: sha256_hex(&plan_bytes),
        window_experiment_sha256: text(&window, "experiment_sha256", "window")?.to_owned(),
        window_started_unix_ms: count(&window, "started_unix_ms", "window")?,
        window_deadline_unix_ms: count(&window, "deadline_unix_ms", "window")?,
    };
    let excluded = "retained unchanged; excluded from corrected-protocol execution and from \
        headline measurements";
    let mut affected_descendants = vec![Descendant {
        kind: "fitting_input_manifest".into(),
        sha256: manifest_sha256.clone(),
        disposition: excluded.into(),
    }];
    for m in &closure.members {
        affected_descendants.push(Descendant {
            kind: format!("projected_fitting_input:{}", m.dataset),
            sha256: m.raw_sha256.clone(),
            disposition: excluded.into(),
        });
        for (k, fold) in m.gp_fold_sha256.iter().enumerate() {
            affected_descendants.push(Descendant {
                kind: format!("projected_inner_fold_input:{}:{k}", m.dataset),
                sha256: fold.clone(),
                disposition: excluded.into(),
            });
        }
    }
    affected_descendants.push(Descendant {
        kind: "v2_plan".into(),
        sha256: study.plan_sha256.clone(),
        disposition: "retained and reportable; never executed again (v3 refuses v2 plans)".into(),
    });
    let proof_sha = sha256_hex(&repository[4]);
    ensure!(
        planner_proof["positive_plan_exit"] == 0 && planner_proof["execution_started"] == false,
        "planner local proof outcome differs from the recorded one"
    );
    affected_descendants.push(Descendant {
        kind: "v3_local_plan_proof_built_on_the_retained_projection".into(),
        sha256: proof_sha,
        disposition: "a local v3 plan accepted this closure before the replay verifier \
            existed; no execution started; superseded by the corrected protocol"
            .into(),
    });
    let mut disposition = HistoricalDisposition {
        schema: DISPOSITION_SCHEMA.into(),
        disposition_id: String::new(),
        study,
        input_closure: closure,
        observed,
        execution_extent: vec![
            "planner staging parsed every development target, including the cut-0 outer \
             scoring labels, before projecting fitting rows; the paired-plan helper constructed \
             the hold partition (deviation record)"
                .into(),
            "the v2 plan was built and its single execution window was admitted".into(),
            "the controller exited with code 1 on an immutable window-receipt collision before \
             CUDA model loading; no direct request, full-GP arm or prediction batch executed"
                .into(),
        ],
        affected_descendants,
        unknowns: vec![
            "whether the parsed outer labels influenced any retained projected byte is not \
             established; no access log exists beyond the deviation record"
                .into(),
            "whether any other process read the development partitions during staging is \
             unknown"
                .into(),
            "encoder, teacher and checkpoint exposure of the ten members remains unknown \
             (regression release family registry)"
                .into(),
        ],
        classification: Classification {
            contamination_inferred: false,
            protocol_compliant: false,
            qualified_measurement: false,
            excluded_from_headline: true,
            original_result_reclassified: false,
            historical_exposure: "outer scoring labels parsed during staging; downstream use \
                unknown"
                .into(),
        },
        evidence,
    };
    disposition.disposition_id = disposition.compute_id()?;
    disposition.validate()?;
    Ok(disposition)
}
