fn canonical<T: Serialize>(value: &T) -> Result<Vec<u8>> {
    canonical_json(&serde_json::to_value(value)?)
}

/// Identity over the canonical body with `field` removed.
fn identity<T: Serialize>(value: &T, field: &str) -> Result<String> {
    let mut body = serde_json::to_value(value)?;
    body.as_object_mut()
        .context("document is not an object")?
        .remove(field);
    Ok(sha256_hex(&canonical_json(&body)?))
}

fn open_document<T: Serialize + serde::de::DeserializeOwned>(
    bytes: &[u8],
    schema: &str,
    what: &str,
) -> Result<T> {
    let value: Value = serde_json::from_slice(bytes).with_context(|| format!("parse {what}"))?;
    ensure!(
        value.get("schema").and_then(Value::as_str) == Some(schema),
        "not a {what} (expected schema {schema})"
    );
    let parsed: T = serde_json::from_value(value).with_context(|| format!("{what} fields"))?;
    ensure!(
        canonical(&parsed)? == bytes,
        "{what} bytes are not the canonical encoding of their content"
    );
    Ok(parsed)
}

fn is_git_sha(value: &str) -> bool {
    value.len() == 40
        && value
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

