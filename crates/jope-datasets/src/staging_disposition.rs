#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CorrectedProtocol {
    pub schema: String,
    pub protocol_id: String,
    /// The historical disposition this protocol supersedes for execution only.
    pub historical_disposition_id: String,
    pub projection_protocol: String,
    pub fitting_inputs_schema: String,
    pub requirements: Vec<String>,
    pub forbidden_projection_sources: Vec<String>,
    pub forbidden_closure_sha256: Vec<String>,
    pub forbidden_windows: Vec<String>,
    pub window_policy: String,
}

const REQUIREMENTS: [&str; 6] = [
    "fitting inputs are pre-projected before any worker or planner starts",
    "no development or sealed target table is opened by the planner or worker",
    "outer (cut-0) scoring labels are never parsed during staging",
    "split membership is consumed label-free",
    "no object produced by the historical staging path is reused",
    "the run receives its own identity and its own original execution window",
];

impl CorrectedProtocol {
    /// The protocol is a pure function of the disposition and fixed rules.
    pub fn derive(disposition: &HistoricalDisposition) -> Result<Self> {
        disposition.validate()?;
        let mut protocol = Self {
            schema: PROTOCOL_SCHEMA.into(),
            protocol_id: String::new(),
            historical_disposition_id: disposition.disposition_id.clone(),
            projection_protocol: PROJECTION_PROTOCOL.into(),
            fitting_inputs_schema: FITTING_INPUTS_SCHEMA.into(),
            requirements: REQUIREMENTS.iter().map(|r| r.to_string()).collect(),
            forbidden_projection_sources: vec![disposition.study.source_sha.clone()],
            forbidden_closure_sha256: disposition.staging_products().into_iter().collect(),
            forbidden_windows: vec![disposition.study.window_experiment_sha256.clone()],
            window_policy: "a corrected run is admitted later with its own original window; \
                the historical window is never resumed or reused"
                .into(),
        };
        protocol.protocol_id = identity(&protocol, "protocol_id")?;
        Ok(protocol)
    }

    pub fn open(bytes: &[u8], disposition: &HistoricalDisposition) -> Result<Self> {
        let protocol: Self =
            open_document(bytes, PROTOCOL_SCHEMA, "fitting-only staging protocol")?;
        ensure!(
            protocol == Self::derive(disposition)?,
            "the protocol is not the one derived from this historical disposition"
        );
        Ok(protocol)
    }

    pub fn encode(&self) -> Result<Vec<u8>> {
        canonical(self)
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CorrectedRun {
    pub schema: String,
    pub run_id: String,
    pub protocol_id: String,
    pub closure: RunClosure,
    /// The run's own admitted window; `None` until admission.
    pub window_experiment_sha256: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RunClosure {
    pub manifest_sha256: String,
    pub projection_source_sha: String,
    pub projection_protocol: String,
    pub attestation: ProjectionAttestation,
}

/// The projecting producer's declaration. Recorded and required; a digest
/// authenticates bytes, not the truth of this declaration.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProjectionAttestation {
    pub inputs_pre_projected: bool,
    pub outer_scoring_labels_parsed: bool,
    pub development_targets_parsed_outside_fitting_rows: bool,
    pub sealed_tables_opened: bool,
}

impl CorrectedRun {
    pub fn new(
        protocol: &CorrectedProtocol,
        closure: RunClosure,
        window: Option<String>,
    ) -> Result<Self> {
        let mut run = Self {
            schema: RUN_SCHEMA.into(),
            run_id: String::new(),
            protocol_id: protocol.protocol_id.clone(),
            closure,
            window_experiment_sha256: window,
        };
        run.run_id = identity(&run, "run_id")?;
        Ok(run)
    }

    pub fn open(bytes: &[u8]) -> Result<Self> {
        let run: Self = open_document(bytes, RUN_SCHEMA, "fitting-only staging run")?;
        ensure!(
            run.run_id == identity(&run, "run_id")?,
            "run identity does not match its content"
        );
        Ok(run)
    }

    pub fn encode(&self) -> Result<Vec<u8>> {
        canonical(self)
    }
}

/// Every object digest a fitting-input manifest names, with its role.
fn closure_objects(manifest: &Value) -> Result<Vec<(String, String)>> {
    let mut objects = Vec::new();
    for input in manifest["inputs"]
        .as_array()
        .context("fitting manifest inputs absent")?
    {
        let id = input["id"].as_str().context("fitting input id")?;
        objects.push((
            format!("{id}: projected fitting input"),
            input["raw"]["sha256"]
                .as_str()
                .context("fitting input digest")?
                .to_owned(),
        ));
        if let Some(folds) = input["gp"]["folds"].as_array() {
            for (k, fold) in folds.iter().enumerate() {
                objects.push((
                    format!("{id}: inner fold {k} input"),
                    fold[0]["sha256"]
                        .as_str()
                        .context("inner fold digest")?
                        .to_owned(),
                ));
            }
        }
    }
    Ok(objects)
}

/// Replay check of an input closure (a fitting-input manifest's exact bytes)
/// against the corrected protocol: the historical closure, its projection
/// source or any object it produced is rejected.
pub fn verify_closure(protocol: &CorrectedProtocol, manifest_bytes: &[u8]) -> Result<Value> {
    let manifest_sha256 = sha256_hex(manifest_bytes);
    let forbidden: BTreeSet<&str> = protocol
        .forbidden_closure_sha256
        .iter()
        .map(String::as_str)
        .collect();
    ensure!(
        !forbidden.contains(manifest_sha256.as_str()),
        "the historical input closure (manifest {manifest_sha256}) cannot be replayed under the \
         corrected fitting-only protocol"
    );
    let manifest: Value =
        serde_json::from_slice(manifest_bytes).context("parse fitting-input manifest")?;
    ensure!(
        manifest["schema"] == protocol.fitting_inputs_schema.as_str(),
        "not a pinned fitting-input manifest"
    );
    let source = manifest["projection_source_sha"]
        .as_str()
        .context("projection source absent")?;
    ensure!(
        !protocol
            .forbidden_projection_sources
            .iter()
            .any(|s| s == source),
        "the closure was projected by the historical staging source {source}"
    );
    let objects = closure_objects(&manifest)?;
    for (role, digest) in &objects {
        ensure!(
            !forbidden.contains(digest.as_str()),
            "{role} {digest} was produced by the historical staging path"
        );
    }
    Ok(
        json!({"manifest_sha256":manifest_sha256,"projection_source_sha":source,
        "objects_checked":objects.len()}),
    )
}

const COMMITTED_DISPOSITION: &[u8] =
    include_bytes!("../releases/staging-disposition/historical-gpu-staging-20260925.json");
const COMMITTED_PROTOCOL: &[u8] =
    include_bytes!("../releases/staging-disposition/fitting-only-staging-protocol-v1.json");

/// The committed historical disposition and corrected protocol, embedded at
/// build time and opened with every identity check, so a consumer cannot be
/// pointed at another pair.
pub fn committed() -> Result<(HistoricalDisposition, CorrectedProtocol)> {
    let disposition = HistoricalDisposition::open(COMMITTED_DISPOSITION)?;
    let protocol = CorrectedProtocol::open(COMMITTED_PROTOCOL, &disposition)?;
    Ok((disposition, protocol))
}

/// Refuse every pinned object the historical staging path produced, for a
/// consumer that holds pinned digests (a plan) rather than the manifest bytes.
/// Returns the number of objects checked.
pub fn refuse_historical_objects<'a>(
    protocol: &CorrectedProtocol,
    objects: impl IntoIterator<Item = (String, &'a str)>,
) -> Result<usize> {
    let mut checked = 0;
    for (role, digest) in objects {
        ensure!(
            !protocol
                .forbidden_closure_sha256
                .iter()
                .any(|f| f == digest),
            "{role} {digest} was produced by the historical staging path"
        );
        checked += 1;
    }
    Ok(checked)
}

/// The producer's corrected-run attestation (W1-T07): emitted by the component
/// that projected a fitting-input closure, for exactly those manifest bytes and
/// that manifest's projection source. The closure is checked against the
/// protocol first, so a historical closure cannot be attested. The fitting-only
/// declaration is the producer's: recorded and required, not independently
/// proven. The returned run passes [`verify_corrected_run`] only if the
/// declaration is a fitting-only projection.
pub fn attest_corrected_run(
    protocol: &CorrectedProtocol,
    manifest_bytes: &[u8],
    attestation: ProjectionAttestation,
    window: Option<String>,
) -> Result<CorrectedRun> {
    let checked = verify_closure(protocol, manifest_bytes)?;
    CorrectedRun::new(
        protocol,
        RunClosure {
            manifest_sha256: sha256_hex(manifest_bytes),
            projection_source_sha: checked["projection_source_sha"]
                .as_str()
                .context("projection source absent")?
                .to_owned(),
            projection_protocol: protocol.projection_protocol.clone(),
            attestation,
        },
        window,
    )
}

/// Accept a corrected run only under this protocol, with a non-historical
/// closure, a fitting-only projection declaration and its own window.
pub fn verify_corrected_run(
    disposition: &HistoricalDisposition,
    protocol: &CorrectedProtocol,
    run_bytes: &[u8],
    manifest_bytes: &[u8],
) -> Result<Value> {
    disposition.validate()?;
    ensure!(
        *protocol == CorrectedProtocol::derive(disposition)?,
        "the protocol is not the one derived from this historical disposition"
    );
    let run = CorrectedRun::open(run_bytes)?;
    ensure!(
        run.protocol_id == protocol.protocol_id,
        "the run is not under the corrected protocol (historical and corrected identities are \
         not interchangeable)"
    );
    ensure!(
        run.run_id != disposition.disposition_id
            && run.run_id != protocol.protocol_id
            && !protocol.forbidden_closure_sha256.contains(&run.run_id),
        "the run reuses a historical identity"
    );
    if let Some(window) = &run.window_experiment_sha256 {
        ensure!(
            is_sha256(window) && !protocol.forbidden_windows.contains(window),
            "the run claims the historical execution window"
        );
    }
    ensure!(
        sha256_hex(manifest_bytes) == run.closure.manifest_sha256,
        "the closure bytes are not the run's pinned manifest"
    );
    let checked = verify_closure(protocol, manifest_bytes)?;
    ensure!(
        checked["projection_source_sha"] == run.closure.projection_source_sha.as_str(),
        "the run declares another projection source than its manifest"
    );
    let a = &run.closure.attestation;
    ensure!(
        run.closure.projection_protocol == protocol.projection_protocol
            && a.inputs_pre_projected
            && !a.outer_scoring_labels_parsed
            && !a.development_targets_parsed_outside_fitting_rows
            && !a.sealed_tables_opened,
        "the run does not declare a fitting-only projection"
    );
    Ok(
        json!({"accepted":true,"run_id":run.run_id,"protocol_id":protocol.protocol_id,
        "historical_disposition_id":disposition.disposition_id,
        "manifest_sha256":checked["manifest_sha256"],"objects_checked":checked["objects_checked"],
        "window_experiment_sha256":run.window_experiment_sha256,
        "attestation":"producer-declared; recorded and required, not independently proven"}),
    )
}

