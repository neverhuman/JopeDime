//! The CI fixture model set (SPECIFICATION.md §15.4): small deterministic safetensors files in
//! the real cache layout, so the PR lane packs, signs, verifies and authenticates assets with the
//! same code as a release, and no real weight ever reaches an untrusted runner.
//!
//! The bundle manifests are committed (`deploy/appliance/fixtures/bundles/*.json`); `write`
//! regenerates the bytes and refuses if they no longer match those manifests.
use anyhow::{ensure, Context, Result};
use serde_json::json;
use std::path::Path;

/// A deterministic stream (64-bit LCG), identical on every run and platform.
struct Stream(u64);

impl Stream {
    fn next_f32(&mut self) -> f32 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        ((self.0 >> 40) as f32 / (1u64 << 24) as f32) * 2.0 - 1.0
    }
}

/// A safetensors file of (name, dtype, shape) tensors with deterministic values.
fn safetensors(seed: u64, tensors: &[(&str, &str, &[usize])]) -> Vec<u8> {
    let mut stream = Stream(seed);
    let mut header = serde_json::Map::new();
    let mut data = Vec::new();
    for (name, dtype, shape) in tensors {
        let count: usize = shape.iter().product();
        let start = data.len();
        for _ in 0..count {
            let value = stream.next_f32();
            match *dtype {
                "F32" => data.extend_from_slice(&value.to_le_bytes()),
                // bf16: the top half of the f32 bits.
                "BF16" => data.extend_from_slice(&value.to_bits().to_le_bytes()[2..4]),
                _ => unreachable!("fixture dtypes are F32 and BF16"),
            }
        }
        header.insert(
            (*name).to_owned(),
            json!({"dtype": dtype, "shape": shape, "data_offsets": [start, data.len()]}),
        );
    }
    header.insert(
        "__metadata__".into(),
        json!({"generator": "jope-dist fixture"}),
    );
    let header = serde_json::to_vec(&header).expect("header serializes");
    let mut out = (header.len() as u64).to_le_bytes().to_vec();
    out.extend_from_slice(&header);
    out.extend_from_slice(&data);
    out
}

pub struct FixtureFile {
    pub bundle: &'static str,
    pub path: &'static str,
    pub kind: &'static str,
    pub bytes: Vec<u8>,
}

pub fn files() -> Vec<FixtureFile> {
    vec![
        FixtureFile {
            bundle: "fixture-encoder",
            path: "encoder.safetensors",
            kind: "model",
            bytes: safetensors(
                1,
                &[
                    ("blocks.0.weight", "F32", &[64, 48]),
                    ("blocks.0.bias", "F32", &[64]),
                    ("emb_head.weight", "BF16", &[32, 64]),
                ],
            ),
        },
        FixtureFile {
            bundle: "fixture-encoder",
            path: "encoder.config.json",
            kind: "config",
            bytes: br#"{"architecture":"fixture-encoder","version":1,"dim":64}"#.to_vec(),
        },
        FixtureFile {
            bundle: "fixture-policy",
            path: "policy.safetensors",
            kind: "model",
            bytes: safetensors(
                2,
                &[
                    ("layers.0.attn.weight", "F32", &[96, 96]),
                    ("layers.0.ffn.weight", "F32", &[96, 128]),
                ],
            ),
        },
    ]
}

/// The `jope.model-bundle/v2` manifest of one fixture bundle.
pub fn manifest(bundle: &str) -> serde_json::Value {
    let files: Vec<serde_json::Value> = files()
        .into_iter()
        .filter(|f| f.bundle == bundle)
        .map(|f| {
            json!({
                "path": f.path,
                "sha256": jope_assets::sha256_hex(&f.bytes),
                "bytes": f.bytes.len(),
                "kind": f.kind,
                "license": {
                    "spdx_expression": "LicenseRef-Jope-Fixture",
                    "redistribution": "permitted",
                },
            })
        })
        .collect();
    json!({
        "schema": "jope.model-bundle/v2",
        "bundle_id": bundle,
        "description": "Deterministic CI fixture generated by `jope-dist fixture`; not a model.",
        "files": files,
    })
}

pub const BUNDLES: [&str; 2] = ["fixture-encoder", "fixture-policy"];

/// Canonical manifest text.
pub fn manifest_text(bundle: &str) -> String {
    let mut text = serde_json::to_string_pretty(&manifest(bundle)).expect("serializes");
    text.push('\n');
    text
}

/// Write the fixture files under `<models>/bundles/<bundle>/<path>` after checking the
/// committed manifests in `manifests` still describe them.
pub fn write(models: &Path, manifests: &Path) -> Result<()> {
    for bundle in BUNDLES {
        let path = manifests.join(format!("{bundle}.json"));
        let committed =
            std::fs::read_to_string(&path).with_context(|| format!("read {}", path.display()))?;
        ensure!(
            committed == manifest_text(bundle),
            "{} no longer matches the generated fixture; run `jope-dist fixture --write-manifests`",
            path.display()
        );
    }
    for file in files() {
        let target = models.join("bundles").join(file.bundle).join(file.path);
        std::fs::create_dir_all(target.parent().context("a bundle file has a parent")?)?;
        std::fs::write(&target, &file.bytes)
            .with_context(|| format!("write {}", target.display()))?;
    }
    Ok(())
}

/// Regenerate the committed manifests.
pub fn write_manifests(manifests: &Path) -> Result<()> {
    std::fs::create_dir_all(manifests)?;
    for bundle in BUNDLES {
        std::fs::write(
            manifests.join(format!("{bundle}.json")),
            manifest_text(bundle),
        )?;
    }
    Ok(())
}
