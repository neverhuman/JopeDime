use super::*;

#[derive(Clone, Copy)]
pub(super) struct RankInput<'a> {
    pub(super) root: &'a Path,
    pub(super) corpus: &'a Path,
    pub(super) run: &'a Path,
    pub(super) launch: &'a Path,
    pub(super) rank: usize,
    pub(super) world: usize,
    pub(super) micro: usize,
    pub(super) steps: usize,
    pub(super) checkpoint_steps: usize,
    pub(super) resume: bool,
    pub(super) initialize: Option<&'a Path>,
    pub(super) global_batch: usize,
    pub(super) batch_qualification: bool,
    pub(super) replay_policy: Option<&'a Path>,
    pub(super) native_stop: Option<&'a std::sync::atomic::AtomicBool>,
    pub(super) verified_native_continuation: bool,
    pub(super) declared_mode: Option<continuation::Mode>,
    pub(super) assignment: Option<&'a topology::Assignment>,
    pub(super) admitted: Option<&'a crate::native_loop::bounded::launch::AdmittedBootstrap>,
    pub(super) partition_version: partition::Version,
    pub(super) bounded_training:
        Option<&'a crate::native_loop::bounded::training_run::BoundedTraining>,
}

pub(super) struct RankPreflight {
    pub(super) communicator: CommunicatorSource,
    pub(super) execution: partition::Execution,
    pub(super) policy: Option<Value>,
    pub(super) policy_sha: Option<String>,
    pub(super) replay: Option<Value>,
    pub(super) seed: u64,
    pub(super) corpus_hash: String,
    pub(super) resident: std::rc::Rc<(
        crate::teaching_store::Index,
        crate::teaching_store::TeachingRecords,
    )>,
    pub(super) vocabulary: crate::grammar::Vocab,
    pub(super) frozen_inputs: Value,
    pub(super) frozen_inputs_sha: String,
    pub(super) families: BTreeMap<String, Vec<usize>>,
    pub(super) validation: BTreeMap<String, Vec<usize>>,
    pub(super) teacher_family: BTreeMap<usize, String>,
    pub(super) fresh: BTreeMap<String, Vec<usize>>,
    pub(super) fresh_by_teacher: BTreeMap<usize, Vec<usize>>,
    pub(super) fresh_records: std::collections::BTreeSet<usize>,
    pub(super) balanced: bool,
    pub(super) epoch_steps: usize,
    pub(super) fixed_panel: Option<ValidationPanel>,
    pub(super) panel_sha256: Option<String>,
    pub(super) config: Config,
    pub(super) recovered_continuation: Option<Value>,
    pub(super) mode: continuation::Mode,
    pub(super) declaration: Value,
    pub(super) objective_sha: String,
    pub(super) continuity: Value,
    pub(super) selected_checkpoint: Option<PathBuf>,
    pub(super) selected_state_sha: Option<String>,
    pub(super) selected_state: Option<Value>,
    pub(super) exposure_baseline: Option<crate::training_exposure::Counts>,
    pub(super) family_baseline: crate::training_exposure::FamilyGroups,
    pub(super) family_baseline_known: bool,
}

pub(super) struct RankInitialized {
    pub(super) preflight: RankPreflight,
    pub(super) device: Device,
    pub(super) vs: nn::VarStore,
    pub(super) model: Policy,
    pub(super) optimizer: AdamW,
    pub(super) initialization_path: PathBuf,
    pub(super) initialization: Value,
    pub(super) sampling_offset: usize,
    pub(super) steps: usize,
}
