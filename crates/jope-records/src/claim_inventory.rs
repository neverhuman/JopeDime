//! `claim-inventory`: the capability, KPI and contribution sentence inventory, generated from
//! the claims record (W12-T01).
//!
//! Every sentence is rendered only from a record that [`claims::verify`] accepts, together with
//! the bindings the claim schema requires: subject, metric, units, denominator, comparison,
//! baseline, input scope, source commit, time, uncertainty, limitations, stage and evidence.
//! The inventory is regenerated from those fields alone, so a sentence whose scope, subject,
//! source or denominator changed is a different entry; nothing is carried over because an
//! artifact or a date matches. Only `active` claims are publishable; revoked and superseded
//! claims are listed as withdrawn. The committed view is checked (or rewritten with `--write`)
//! like `STATUS.md` and `PROGRESS.md`.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use crate::py;
use crate::pyjson::{self, Dict, Value};
use crate::{claims, require, Error, Result};

/// The command that regenerates the committed inventory.
pub const GENERATOR: &str = "cargo run -q --locked -p jope-records -- claim-inventory --write";
/// The inventory, beside the claims record.
pub const FILE: &str = "INVENTORY.md";

/// Where the inventory of the claims record at `claims` lives.
pub fn target(claims: &Path) -> PathBuf {
    claims.with_file_name(FILE)
}

/// One table cell: text as is (one line, pipes escaped), `null` as `none`, anything else as
/// sorted compact JSON.
fn cell(value: Option<&Value>) -> String {
    let text = match value {
        None | Some(Value::Null) => "none".to_owned(),
        Some(value) => match value.as_str() {
            Some(text) => text.to_owned(),
            None => pyjson::dumps(value, true, None),
        },
    };
    text.replace('\n', " ").replace('|', "\\|")
}

fn field<'a>(claim: &'a Value, name: &str) -> Option<&'a Value> {
    claim.get(name)
}

fn text(claim: &Value, name: &str) -> String {
    field(claim, name)
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_owned()
}

/// Render the inventory of the claims record at `path`; the record is verified first, with
/// evidence paths relative to `root` (the repository by default).
pub fn render(path: &Path, root: Option<&Path>) -> Result<(String, Value)> {
    claims::verify(path, root, false)?;
    let document = py::load_json(path)?;
    let claims = document
        .get("claims")
        .and_then(Value::as_list)
        .cloned()
        .ok_or_else(|| Error::Shape("claims list".into()))?;
    let empty = Dict::new();
    let evidence = document
        .get("evidence")
        .and_then(Value::as_dict)
        .unwrap_or(&empty);
    let mut counts: BTreeMap<(String, String), usize> = BTreeMap::new();
    for claim in &claims {
        *counts
            .entry((text(claim, "stage"), text(claim, "status")))
            .or_default() += 1;
    }
    let mut lines: Vec<String> = vec![
        "# Capability, KPI and contribution claim inventory".into(),
        String::new(),
        format!("Generated by `{GENERATOR}` from the verified `claims.json`; do not edit."),
        "A sentence may be published only as rendered here: with every binding below, at the stage its evidence supports, and only while its status is `active`. Changing its subject, scope, source or denominator makes it a different claim that needs its own evidence.".into(),
        String::new(),
        "| Stage | Status | Claims |".into(),
        "|---|---|---|".into(),
    ];
    for ((stage, status), count) in &counts {
        lines.push(format!("| {stage} | {status} | {count} |"));
    }
    for (heading, publishable) in [("Publishable (active)", true), ("Withdrawn", false)] {
        let group: Vec<&Value> = claims
            .iter()
            .filter(|claim| (text(claim, "status") == "active") == publishable)
            .collect();
        lines.push(String::new());
        lines.push(format!("## {heading}"));
        if group.is_empty() {
            lines.push(String::new());
            lines.push("None.".into());
        }
        for claim in group {
            lines.push(String::new());
            lines.push(format!("### {}", text(claim, "id")));
            lines.push(String::new());
            lines.push(format!("> {}", cell(field(claim, "statement"))));
            lines.push(String::new());
            lines.push("| Binding | Value |".into());
            lines.push("|---|---|".into());
            for (label, name) in [
                ("Status", "status"),
                ("Stage", "stage"),
                ("Subject", "subject"),
                ("Metric", "metric"),
                ("Units", "units"),
                ("Denominator", "denominator"),
                ("Comparison", "comparison"),
                ("Baseline", "baseline"),
                ("Input scope", "scope"),
                ("Source commit", "source_commit"),
                ("Observed (UTC)", "observed_utc"),
                ("Uncertainty", "uncertainty"),
            ] {
                lines.push(format!("| {label} | {} |", cell(field(claim, name))));
            }
            let nodes: Vec<String> = field(claim, "evidence")
                .and_then(Value::as_list)
                .map(|list| {
                    list.iter()
                        .map(|node| {
                            let id = node.as_str().unwrap_or_default();
                            let kind = evidence
                                .get(id)
                                .and_then(|n| n.get("kind"))
                                .and_then(Value::as_str)
                                .unwrap_or("unknown");
                            format!("{id} ({kind})")
                        })
                        .collect()
                })
                .unwrap_or_default();
            lines.push(format!(
                "| Evidence | {} |",
                cell(Some(&Value::from(nodes.join(", "))))
            ));
            lines.push(String::new());
            lines.push("Limitations:".into());
            for limitation in field(claim, "limitations")
                .and_then(Value::as_list)
                .map(Vec::as_slice)
                .unwrap_or_default()
            {
                lines.push(format!("- {}", cell(Some(limitation))));
            }
        }
    }
    let mut summary = Dict::new();
    summary.insert("claims", claims.len().into());
    summary.insert(
        "publishable",
        claims
            .iter()
            .filter(|claim| text(claim, "status") == "active")
            .count()
            .into(),
    );
    summary.insert(
        "scope",
        "sentence inventory from verified claims; publishes nothing".into(),
    );
    Ok((lines.join("\n") + "\n", Value::Dict(summary)))
}

/// Check the committed inventory against `text`, or rewrite it.
pub fn check_or_write(target: &Path, text: &str, write: bool) -> Result<()> {
    if write {
        return std::fs::write(target, text).map_err(|e| Error::io(target, e));
    }
    require!(
        py::read_text(target)? == text,
        "INVENTORY.md is stale; regenerate with --write"
    );
    Ok(())
}
