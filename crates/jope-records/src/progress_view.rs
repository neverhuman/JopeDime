//! `progress-view`: validate the committed remediation records and render `PROGRESS.md` from
//! them (W12-T03).
//!
//! The view composes the findings register, finding dispositions, task status and claims. Each
//! input is first accepted by its own verifier, and the view is regenerated from those validated
//! records only:
//!
//! - A finding counts as closed only through a verified closing disposition. Task states, claims
//!   and this view never close one.
//! - Counts come from record fields, never from titles, notes or key order, so presentation
//!   metadata cannot change them.
//! - The exact input digests are part of the view, so a view is bound to the records it came
//!   from.
//! - Custody verification depends on the host (a CI runner cannot read custody), so the view
//!   shows where evidence lives, never whether this host happened to verify it.

use std::collections::HashSet;
use std::path::{Path, PathBuf};

use crate::py;
use crate::pyjson::{Dict, Value};
use crate::task_status::{self, int_key, Headings, STATES};
use crate::{claims, dispositions, require, Error, Result};

/// The records the view is bound to, relative to the core-IP directory.
pub const INPUTS: [&str; 4] = [
    "findings/register.json",
    "findings/dispositions.json",
    "work-orders/task-status.json",
    "claims/claims.json",
];
/// The generator named in the rendered header.
pub const GENERATOR: &str = "jope-records progress-view";
/// The custody verifier named in the claims section.
pub const CUSTODY_VERIFIER: &str = "jope-records verify-claims --require-custody";

/// Validated inputs of the view.
#[derive(Clone, Debug)]
pub struct Data {
    pub digests: Vec<(&'static str, String)>,
    pub entries: Vec<Value>,
    pub closed: HashSet<String>,
    /// Effective disposition counts (`verify-dispositions`' `dispositions`).
    pub dispositions: Vec<(String, usize)>,
    pub headings: Headings,
    pub tasks: Dict,
    pub claims: Value,
}

/// `W01` (task file prefix) and `W1` (register work package) name the same work order.
fn package(order: &str) -> Result<String> {
    Ok(format!(
        "W{}",
        int_key(order.get(1..).unwrap_or_default(), order)?
    ))
}

/// Run every input's verifier, then load the records the view is rendered from.
pub fn collect(core: &Path) -> Result<Data> {
    let summary = dispositions::verify(&core.join("findings"), false, None)?;
    let record = task_status::verify(&core.join("work-orders"))?;
    let claims_path = core.join("claims").join("claims.json");
    let repository: PathBuf = core
        .ancestors()
        .nth(3)
        .map(Path::to_path_buf)
        .ok_or_else(|| {
            Error::Shape(format!(
                "{}: no repository root above core-ip",
                core.display()
            ))
        })?;
    claims::verify(&claims_path, Some(&repository), false)?;
    let register = py::load_json(&core.join("findings").join("register.json"))?;
    let claims = py::load_json(&claims_path)?;
    let mut digests = Vec::new();
    for name in INPUTS {
        digests.push((name, py::sha256_hex(&py::read_bytes(&core.join(name))?)));
    }
    let entries = register
        .get("entries")
        .and_then(Value::as_list)
        .cloned()
        .ok_or_else(|| Error::Shape("register: entries is not a list".into()))?;
    Ok(Data {
        digests,
        entries,
        closed: summary.closed_findings.into_iter().collect(),
        dispositions: summary.dispositions.into_iter().collect(),
        headings: record.headings,
        tasks: record.tasks,
        claims,
    })
}

fn text(value: Option<&Value>) -> String {
    value.map_or_else(|| "None".to_owned(), Value::py_str)
}

fn states(tasks: &Dict, task: &str) -> Vec<String> {
    tasks
        .get(task)
        .and_then(|t| t.get("states"))
        .and_then(Value::as_list)
        .map(|s| s.iter().map(Value::py_str).collect())
        .unwrap_or_default()
}

/// Render `PROGRESS.md` from validated inputs.
pub fn render(data: &Data) -> Result<String> {
    let Data {
        entries,
        closed,
        headings,
        tasks,
        ..
    } = data;
    let work_package = |entry: &Value| text(entry.get("work_package"));
    let mut packages: Vec<(i64, String)> = Vec::new();
    let mut names: Vec<String> = entries.iter().map(work_package).collect();
    for (_, heading) in headings.iter() {
        names.push(package(&heading.order)?);
    }
    for name in names {
        if !packages.iter().any(|(_, p)| *p == name) {
            packages.push((int_key(name.get(1..).unwrap_or_default(), &name)?, name));
        }
    }
    packages.sort();

    let mut lines: Vec<String> = vec![
        "# Regression remediation progress view".into(),
        String::new(),
        format!("Generated by `{GENERATOR}` from the validated records below; do not edit."),
        "A finding closes only through a verified closing disposition in `findings/dispositions.json`;".into(),
        "task states, claims and this view never close one. Fixture proof is not CI verification, and".into(),
        "neither is live qualification.".into(),
        String::new(),
        "## Inputs".into(),
        String::new(),
        "| Record | SHA-256 |".into(),
        "|---|---|".into(),
    ];
    for (name, digest) in &data.digests {
        lines.push(format!("| `{name}` | `{digest}` |"));
    }
    lines.push(String::new());

    let mut header: Vec<&str> = vec![
        "Work order",
        "Gaps",
        "Improvements",
        "Open",
        "Closed",
        "Tasks",
    ];
    header.extend(STATES);
    lines.extend([
        "## Findings and tasks by primary work order".into(),
        String::new(),
        "Task columns count tasks holding each state; a task can hold several.".into(),
        String::new(),
        format!("| {} |", header.join(" | ")),
        format!("|---|{}", "---:|".repeat(header.len() - 1)),
    ]);
    let mut totals = vec![0usize; header.len() - 1];
    for (_, name) in &packages {
        let owned: Vec<&Value> = entries
            .iter()
            .filter(|e| work_package(e) == *name)
            .collect();
        let mut owned_tasks = Vec::new();
        for (id, heading) in headings.iter() {
            if package(&heading.order)? == *name {
                owned_tasks.push(id);
            }
        }
        let kind = |e: &&Value, k: &str| e.get("kind") == Some(&Value::from(k));
        let is_closed = |e: &&Value| {
            e.get("id")
                .and_then(Value::as_str)
                .is_some_and(|id| closed.contains(id))
        };
        let mut row = vec![
            owned.iter().filter(|e| kind(e, "gap")).count(),
            owned.iter().filter(|e| kind(e, "improvement")).count(),
            owned.iter().filter(|e| !is_closed(e)).count(),
            owned.iter().filter(|e| is_closed(e)).count(),
            owned_tasks.len(),
        ];
        for state in STATES {
            row.push(
                owned_tasks
                    .iter()
                    .filter(|t| states(tasks, t).iter().any(|s| s == state))
                    .count(),
            );
        }
        for (total, value) in totals.iter_mut().zip(&row) {
            *total += value;
        }
        let cells: Vec<String> = row.iter().map(ToString::to_string).collect();
        lines.push(format!("| {name} | {} |", cells.join(" | ")));
    }
    let bold: Vec<String> = totals.iter().map(|v| format!("**{v}**")).collect();
    lines.push(format!("| **Total** | {} |", bold.join(" | ")));
    lines.push(String::new());

    let mut blocked: Vec<((i64, i64), &str)> = Vec::new();
    for task in tasks.keys() {
        if states(tasks, task).iter().any(|s| s == "blocked") {
            let order = task
                .get(1..)
                .unwrap_or_default()
                .split('-')
                .next()
                .unwrap_or_default();
            let number = task.split("-T").nth(1).unwrap_or_default();
            blocked.push(((int_key(order, task)?, int_key(number, task)?), task));
        }
    }
    blocked.sort_by_key(|(key, _)| *key);
    lines.extend([
        "## Pending gates".into(),
        String::new(),
        "| Task | Blocker |".into(),
        "|---|---|".into(),
    ]);
    if blocked.is_empty() {
        lines.push("| — | — |".into());
    }
    for (_, task) in &blocked {
        let title = &headings
            .get(task)
            .expect("verified: records equal headings")
            .title;
        let blocker = text(tasks.get(task).and_then(|t| t.get("blocker")));
        lines.push(format!("| {task} {title} | {blocker} |"));
    }
    lines.push(String::new());

    let evidence = data
        .claims
        .get("evidence")
        .ok_or_else(|| Error::Shape("claims: no evidence map".into()))?;
    lines.extend([
        "## Claims".into(),
        String::new(),
        "Evidence location is shown, not this host's verification result: custody evidence is"
            .into(),
        format!("verified by `{CUSTODY_VERIFIER}` where custody is readable."),
        String::new(),
        "| Claim | Stage | Status | Evidence (kind, location) |".into(),
        "|---|---|---|---|".into(),
    ]);
    let mut claim_list: Vec<&Value> = data
        .claims
        .get("claims")
        .and_then(Value::as_list)
        .map(|c| c.iter().collect())
        .unwrap_or_default();
    // Claim IDs were verified; sorting them as strings matches Python's `sorted(key=id)`.
    claim_list.sort_by_key(|c| text(c.get("id")));
    for claim in claim_list {
        let mut cited = Vec::new();
        for node in claim
            .get("evidence")
            .and_then(Value::as_list)
            .into_iter()
            .flatten()
        {
            let id = node.py_str();
            let node = evidence
                .get(&id)
                .ok_or_else(|| Error::Shape(format!("claims: unknown evidence {id}")))?;
            cited.push(format!(
                "{id} ({}, {})",
                text(node.get("kind")),
                text(node.get("location"))
            ));
        }
        lines.push(format!(
            "| {} | {} | {} | {} |",
            text(claim.get("id")),
            text(claim.get("stage")),
            text(claim.get("status")),
            cited.join("; ")
        ));
    }
    lines.push(String::new());

    let planned = tasks
        .keys()
        .filter(|t| states(tasks, t) == ["planned"])
        .count();
    let disposed: usize = data.dispositions.iter().map(|(_, n)| n).sum();
    let findings = entries.len();
    lines.extend([
        "## Not progress".into(),
        String::new(),
        format!(
            "- Tasks still only planned (no commits or evidence): {planned} of {}.",
            tasks.len()
        ),
        format!(
            "- Findings without any disposition record: {} of {findings}.",
            findings - disposed
        ),
        format!("- Findings closed: {} of {findings}.", closed.len()),
        String::new(),
    ]);
    Ok(lines.join("\n"))
}

/// The summary `progress-view` prints.
pub fn summary(data: &Data) -> Value {
    let mut dict = Dict::new();
    dict.insert("findings", data.entries.len().into());
    dict.insert("closed", data.closed.len().into());
    dict.insert("tasks", data.tasks.len().into());
    Value::Dict(dict)
}

/// Compare the committed view with a fresh render, or rewrite it (`--write`).
pub fn check_or_write(core: &Path, text: &str, write: bool) -> Result<()> {
    let target = core.join("work-orders").join("PROGRESS.md");
    if write {
        return std::fs::write(&target, text).map_err(|e| Error::io(&target, e));
    }
    require!(
        py::read_text(&target)? == text,
        "PROGRESS.md is stale; regenerate with --write"
    );
    Ok(())
}
