//! W12-T07: the public synthetic conformance pack, its replay through the receiving validator
//! and the private-canary absence scan. Added (no Python predecessor).

use jope_records::conformance::{check_or_write, pack, replay, scan, tree, INDEX};
use jope_records::pyjson::Value;

use crate::{assert_refused, at, copy_tree, dump_with, load, nth, repo, set};

/// A scratch repository holding a copy of the committed conformance tree.
fn copy() -> tempfile::TempDir {
    let directory = crate::scratch();
    copy_tree(&tree(&repo()), &tree(directory.path()));
    directory
}

#[test]
fn the_committed_pack_is_generated_and_replays_through_the_claims_validator() {
    let repo = repo();
    let files = check_or_write(&repo, false).expect("committed pack is current");
    assert_eq!(files, pack().len());
    assert_eq!(scan(&repo).expect("no canary, every file marked"), files);
    let summary = replay(&repo).expect("every fixture has its recorded outcome");
    let fixtures = load(&tree(&repo).join(INDEX));
    let count = fixtures
        .get("fixtures")
        .and_then(Value::as_list)
        .unwrap()
        .len();
    assert_eq!(summary.get("fixtures"), Some(&Value::from(count)));
    assert_eq!(summary.get("accepted"), Some(&Value::from(1usize)));
    assert_eq!(summary.get("refused"), Some(&Value::from(count - 1)));
    // One fixture per refusal class, all distinct.
    let classes: std::collections::BTreeSet<String> = fixtures
        .get("fixtures")
        .and_then(Value::as_list)
        .unwrap()
        .iter()
        .filter_map(|f| {
            f.get("refusal_class")
                .and_then(Value::as_str)
                .map(str::to_owned)
        })
        .collect();
    assert_eq!(classes.len(), count - 1);
}

#[test]
fn a_fixture_with_another_outcome_than_recorded_fails_the_replay() {
    let scratch = copy();
    let index = tree(scratch.path()).join(INDEX);
    let mut document = load(&index);
    // The accepted control recorded as a refusal, and a refusal recorded as accepted.
    let mut flipped = document.clone();
    let expect = at(nth(at(&mut flipped, "fixtures"), 0), "expect");
    set(expect, "outcome", "refused".into());
    set(expect, "message_contains", "anything".into());
    dump_with(&index, &flipped, true, Some(2));
    assert_refused(replay(scratch.path()), "expected refusal, accepted");
    let expect = at(nth(at(&mut document, "fixtures"), 1), "expect");
    set(expect, "outcome", "accepted".into());
    dump_with(&index, &document, true, Some(2));
    assert_refused(replay(scratch.path()), "expected acceptance, refused");
    // And the drift check sees the edited index.
    assert_refused(
        check_or_write(scratch.path(), false),
        "conformance pack differs from its generator",
    );
}

#[test]
fn a_refusal_for_another_reason_fails_the_replay() {
    let scratch = copy();
    let index = tree(scratch.path()).join(INDEX);
    let mut document = load(&index);
    set(
        at(nth(at(&mut document, "fixtures"), 1), "expect"),
        "message_contains",
        "a message the validator never gives".into(),
    );
    dump_with(&index, &document, true, Some(2));
    assert_refused(replay(scratch.path()), "refused for another reason");
}

#[test]
fn private_canaries_and_unmarked_files_are_refused() {
    // Canary shapes are assembled at run time, so this source itself carries none (the
    // repository's secret and home-path scans read it).
    for (label, text) in [
        (
            "aws-access-key",
            format!("{}{}", "AKIA", "ABCDEFGHIJKLMNOP"),
        ),
        (
            "private-home-path",
            format!("/{}/someone/private.json", "home"),
        ),
        ("private-host", "xbabe2".to_owned()),
        ("object-store-uri", format!("{}://private-bucket/key", "s3")),
        ("custody-root", "jope-rescue-20260921".to_owned()),
        (
            "private-key",
            format!("-----BEGIN RSA {} KEY-----", "PRIVATE"),
        ),
    ] {
        let scratch = copy();
        let index = tree(scratch.path()).join(INDEX);
        let mut document = load(&index);
        set(&mut document, "note", text.as_str().into());
        dump_with(&index, &document, true, Some(2));
        assert_refused(scan(scratch.path()), &format!("private canary {label}"));
    }
    let scratch = copy();
    let stray = tree(scratch.path()).join("claims/stray.json");
    std::fs::write(&stray, "{\"node\": \"unmarked\"}\n").unwrap();
    assert_refused(scan(scratch.path()), "lacks the synthetic identity");
    assert_refused(
        check_or_write(scratch.path(), false),
        "differs from its generator at claims/stray.json",
    );
    // `--write` restores generated bytes but never deletes a stray file.
    assert_refused(
        check_or_write(scratch.path(), true),
        "differs from its generator at claims/stray.json",
    );
    assert!(stray.exists());
    std::fs::remove_file(&stray).unwrap();
    check_or_write(scratch.path(), false).unwrap();
}
