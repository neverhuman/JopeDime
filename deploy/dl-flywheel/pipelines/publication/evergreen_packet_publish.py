 wanted=inventory['rows'];need(len(wanted)==len(rows)==len(c['sequences'])and [r['sequence']for r in rows]==sorted(c['sequences'])and [r['sequence']for r in wanted]==sorted(c['sequences']),'exact selected packet closure')
 need(len(rows)<=release['released_capacity'],'packet exceeds verified released capacity')
 eligible,excluded_cids,excluded_views=check_authority(base,conf);plans=[]
