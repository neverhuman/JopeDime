 progress(base,out,'publishing',done,count,len(plans))
 try:
  with(out/'objects.jsonl').open('xb')as log:
   def append(ref):
    nonlocal count
    log.write(canonical(ref)+b'\n');log.flush();os.fsync(log.fileno());count+=1
   for plan in plans:
    base.tick(deadline);row=plan['row'];refs=[]
    for name,raw in plan['files'].items():
     key=base.PREFIX+'datasets/flywheel/v1/'+row['identity']+'/'+name;ref=put_verified(base,client,key,raw,deadline);append(ref);refs.append(ref)
    receipt={'schema':'jope.flywheel-evergreen-dataset-publication/v1','variant_identity':row['identity'],'content_sha256':row['content_sha'],'metadata_sha256':row['metadata_sha'],
     'sequence':row['sequence'],'parent_lineage_sha256':row['parent'],'generator_config_sha256':GENERATOR_CONFIG_SHA,'publication_helper_sha256':c['helper_sha256'],
     'source_inventory_sha256':c['inventory']['sha256'],'parent_registry':conf['parent_registry'],'objects':refs,'qualification':plan['qualification'],
     'rights':'research','prepared':True,'raw_units':False,'encoders_required_before_dataset_publication':False,'fresh_encodings_required':True,'fresh_gp_evaluations_required':True,'new_gp_labels':0,'teaching_eligible':False,'native_context_admission':'unqualified'}
    raw=canonical(receipt)+b'\n';key=base.PREFIX+'receipts/flywheel-datasets/v1/'+row['identity']+'/'+sha(raw)+'.json';ref=put_verified(base,client,key,raw,deadline);append(ref)
    publication={'qualified':True,'variant_identity':row['identity'],'content_sha256':row['content_sha'],'metadata_sha256':row['metadata_sha'],'s3_receipt':ref,'qualification':plan['qualification'],'publication_helper_sha256':c['helper_sha256']}
    with(out/(row['identity']+'.json')).open('xb')as f:f.write(canonical(publication)+b'\n');f.flush();os.fsync(f.fileno())
    commit_published(W/'data/expansion.sqlite',dbconfig,row,publication,deadline);done.append({'sequence':row['sequence'],'variant_identity':row['identity'],'receipt':ref});progress(base,out,'publishing',done,count,len(plans))
  need(len(done)==len(plans)and count==4*len(plans),'publication closure');base.tick(deadline);progress(base,out,'complete',done,count,len(plans))
 except BaseException as e:progress(base,out,'failed',done,count,len(plans),error=type(e).__name__+': '+str(e));raise

