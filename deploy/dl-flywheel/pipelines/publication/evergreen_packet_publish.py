def validate_dataset(g,row,parent,packed,metadata,generation):
 need(generation['schema']==g.SCHEMA and generation['config_sha256']==GENERATOR_CONFIG_SHA,'generation authority')
 need(generation['sequence']==row['sequence'] and generation['variant_identity']==row['identity'] and generation['parent_lineage_sha256']==row['parent'],'generation row')
 need(generation['encoder_sha256']==sha(packed) and generation['metadata_sha256']==sha(metadata)==row['metadata_sha'],'compressed/metadata binding')
 meta=json.loads(metadata);need(g.canonical(meta)==metadata,'canonical metadata')
 need(meta['parent']==parent and meta['parent_record_sha256']==g.digest(parent),'exact qualified parent')
 need(meta['partition']==parent['partition'] and meta['parent_lineage_sha256']==row['parent'],'inherited lineage partition')
 need(meta['gp_measurements']==0 and type(meta['gp_measurements'])is int and meta['teaching_eligible']is False and meta['inherited_gp_rewards']is False,'generated is not GP/teaching admission')
 need(meta['rights']=='research' and meta['raw_units']is False and meta['prepared']is True and meta['outer_test_rows']==0,'research/trainonly scope')
 with gzip.GzipFile(fileobj=io.BytesIO(packed))as z:raw=z.read(g.MAX_RAW+1)
 need(len(raw)<=g.MAX_RAW and sha(raw)==generation['raw_sha256']==row['content_sha']==meta['content_sha256'],'raw hash')
 # Recompute the pure declared transform from exact authenticated parent bytes.
 # No fitting, native scoring or generated-file writes occur here.
 x,y,folds=g.source(parent);identity,replayed,expected_meta=g.generate(parent,row['ordinal'],x,y,folds)
 need(identity==row['identity']==meta['variant_identity'] and replayed==raw,'deterministic generated bytes')
 expected=g.canonical(expected_meta);expected=expected.encode()if isinstance(expected,str)else expected
 need(expected==metadata,'full transformation metadata differs')
 return {'variant_identity':identity,'content_sha256':sha(raw),'metadata_sha256':sha(metadata),'parent_lineage_sha256':row['parent'],'partition':parent['partition'],
  'rows':meta['rows'],'features':meta['features'],'target_sha256':meta['target_sha256'],'source_target_sha256':meta['source_target_sha256'],'inner_counts':meta['inner_counts'],'outer_test_rows':0,
  'deterministic_replay_exact':True,'new_gp_labels':0,'teaching_eligible':False}

