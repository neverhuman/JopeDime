def preflight(base,g,conf,c,deadline):
 base.tick(deadline);inventory=json.loads(base.bound(c['inventory'],cap=32*base.MIB));need(inventory['config_sha256']==GENERATOR_CONFIG_SHA,'inventory generator binding')
