 byparent={p['parent_lineage_sha256']:p for p in parents};need(len(byparent)==1068,'unique parents');expected_config=g.digest({'config_sha':GENERATOR_CONFIG_SHA,'parents':parents,'target':conf['target'],'backlog':conf['backlog_limit']})
 release=check_release(base,c)
