PREPARED_CONTEXT_KEYS = ("context_sha256", "dataset_hash", "outer_fold", "train_rows", "encoded_features",
                         "candidate_timeout_ms", "evaluator_sha256", "inner_cv_schema")


def project_prepared(src: Any, ref: Mapping | None = None, ctx: str | None = None) -> dict:
    """The cross-check keys of prepared.json's context (nothing else is read). Bytes are verified against
    prepared_ref {sha256, bytes} first; a mismatch is STOP(prepared_pin)."""
    if isinstance(src, (bytes, bytearray)):
        if ref is not None and (common.sha256_bytes(bytes(src)) != ref.get("sha256")
                                or ("bytes" in ref and len(src) != ref["bytes"])):
            raise CorpusStop("prepared.json bytes differ from the epoch prepared_ref", ctx, STOP_PREPARED_PIN)
        try:
            doc = json.loads(src)
        except ValueError as err:
            raise CorpusStop(f"prepared.json is not JSON ({err})", ctx, STOP_SOURCE) from None
    else:
        doc = src
    if isinstance(doc, Mapping) and "context" not in doc and set(doc) <= set(PREPARED_CONTEXT_KEYS):
        return {k: doc.get(k) for k in PREPARED_CONTEXT_KEYS}        # already projected
    context = doc.get("context") if isinstance(doc, Mapping) else None
    if not isinstance(context, Mapping):
        raise CorpusStop("prepared.json has no context object", ctx, STOP_SOURCE)
    return {k: context.get(k) for k in PREPARED_CONTEXT_KEYS}


def load_prepared(path: Path | str, ref: Mapping, ctx: str | None = None) -> dict:
    return project_prepared(Path(path).read_bytes(), ref, ctx)


def check_prepared(prepared: Any, header: Mapping, ctx: Any = None) -> dict:
    """STOP pins between prepared.json and the JTT1 header: train_rows == n_train, encoded_features == p and
    inner_folds == 2 (jtt1_shape); candidate_timeout_ms == 90000 (timeout_pin); evaluator_sha256 (evaluator_pin);
    inner_cv_schema (inner_cv_pin); and, with ctx, context_sha256/dataset_hash/outer_fold (prepared_identity)."""
    p = project_prepared(prepared)
    c = ctx_identity(ctx) if ctx is not None else None
    cid = c.context_sha256 if c is not None else None
    checks: dict[str, bool] = {}

    def need(name: str, ok: bool, kind: str, msg: str) -> None:
        checks[name] = bool(ok)
        if not ok:
            raise CorpusStop(msg, cid, kind)

    def same_int(a: Any, b: Any) -> bool:
        return _is_int(a) and _is_int(b) and a == b

    need("train_rows", same_int(p["train_rows"], header["n_train"]), STOP_JTT1_SHAPE,
         f"JTT1 n_train {header['n_train']} != prepared train_rows {p['train_rows']!r}")
    need("encoded_features", same_int(p["encoded_features"], header["p"]), STOP_JTT1_SHAPE,
         f"JTT1 p {header['p']} != prepared encoded_features {p['encoded_features']!r}")
    need("inner_folds", same_int(header["inner_folds"], INNER_FOLDS), STOP_JTT1_SHAPE,
         f"JTT1 inner_folds {header['inner_folds']} != {INNER_FOLDS}")
    need("candidate_timeout_ms", same_int(p["candidate_timeout_ms"], TIMEOUT_MS), STOP_TIMEOUT_PIN,
         f"candidate_timeout_ms {p['candidate_timeout_ms']!r} != {TIMEOUT_MS}")
    need("evaluator_sha256", p["evaluator_sha256"] == EVALUATOR_SHA256, STOP_EVALUATOR_PIN,
         f"evaluator_sha256 {str(p['evaluator_sha256'])[:16]} != pin {EVALUATOR_SHA256[:16]}")
    need("inner_cv_schema", p["inner_cv_schema"] == INNER_CV_SCHEMA, STOP_INNER_CV_PIN,
         f"inner_cv_schema {p['inner_cv_schema']!r} != {INNER_CV_SCHEMA}")
    if c is not None:
        need("context_sha256", p["context_sha256"] == c.context_sha256, STOP_PREPARED_IDENTITY,
             "prepared.json names another context")
        if c.dataset_hash is not None:
            need("dataset_hash", p["dataset_hash"] == c.dataset_hash, STOP_PREPARED_IDENTITY,
                 "prepared.json names another dataset")
        if c.fold is not None:
            need("outer_fold", same_int(p["outer_fold"], c.fold), STOP_PREPARED_IDENTITY,
                 "prepared.json names another outer fold")
    return checks


@dataclass(frozen=True, eq=False)
class TrainInput:
    """The decodable outer-train part of one JTT1 input: header values, inner-fold labels, X and y of rows
    [0, n_train), the identity hashes, and s_c and eps_c (labels.robust_scale and labels.epsilon of y)."""
    n_train: int
    n_test: int
    p: int
    inner_folds: int
    inner_labels: np.ndarray
    X: np.ndarray
    y: np.ndarray
    raw_sha256: str
    train_rows_sha256: str
    s_c: float
    eps_c: float
    prepared_checks: dict | None = None

    def header(self) -> dict:
        return {"n_train": self.n_train, "n_test": self.n_test, "p": self.p, "inner_folds": self.inner_folds}

    def to_json(self) -> dict:
        """ctx-record jtt1 block (raw_sha256 identifies the whole input; nothing test-derived)."""
        return {**self.header(), "raw_sha256": self.raw_sha256, "train_rows_sha256": self.train_rows_sha256}


def train_input(raw: bytes, prepared: Any = None, ctx: Any = None) -> TrainInput:
    """Decode only the outer-train bytes of a raw JTT1 input (jtt1.train_view: JTT1 magic, exact length, bytes
    [17+n_train, 17+n_train+8(p+1)n_train)), cross-check prepared.json when given, require finite targets
    (STOP nonfinite_target) and compute s_c and eps_c from those n_train rows only."""
    cid = ctx_identity(ctx).context_sha256 if ctx is not None else None
    try:
        h, inner, X, y = jtt1.train_view(raw)
        trs = jtt1.train_rows_sha256(raw)
    except jtt1.JTTError as err:
        raise CorpusStop(str(err), cid, STOP_JTT1) from None
    if h["inner_folds"] != INNER_FOLDS:
        raise CorpusStop(f"JTT1 inner_folds {h['inner_folds']} != {INNER_FOLDS}", cid, STOP_JTT1_SHAPE)
    checks = check_prepared(prepared, h, ctx) if prepared is not None else None
    if not bool(np.all(np.isfinite(y))):
        raise CorpusStop("outer-train targets hold a non-finite value", cid, STOP_NONFINITE_TARGET)
    try:
        s_c = labels.robust_scale(y)
        eps_c = labels.epsilon(y, s_c)
    except labels.LabelError as err:
        raise CorpusStop(str(err), cid, STOP_NONFINITE_TARGET) from None
    return TrainInput(n_train=h["n_train"], n_test=h["n_test"], p=h["p"], inner_folds=h["inner_folds"],
                      inner_labels=inner, X=X, y=y, raw_sha256=common.sha256_bytes(bytes(raw)),
                      train_rows_sha256=trs, s_c=s_c, eps_c=eps_c, prepared_checks=checks)


