_SCALARS = (str, bool, int, float)


def _prune_value(value: Any, sub: Any, path: str) -> Any:
    if sub is True:
        if value is None or isinstance(value, _SCALARS):
            return value
        raise CorpusStop(f"{path}: allowlisted leaf is a {type(value).__name__}, not a JSON scalar", None, STOP_ROW)
    if isinstance(sub, dict):
        if value is None:
            return None
        if not isinstance(value, dict):
            raise CorpusStop(f"{path}: expected an object or null, got {type(value).__name__}", None, STOP_ROW)
        return prune(value, sub, path)
    if isinstance(sub, list) and len(sub) == 1:
        if value is None:
            return None
        if not isinstance(value, list):
            raise CorpusStop(f"{path}: expected a list or null, got {type(value).__name__}", None, STOP_ROW)
        return [_prune_value(v, sub[0], f"{path}[{i}]") for i, v in enumerate(value)]
    raise ValueError(f"{path}: malformed prune spec {sub!r}")


def prune(row: Any, spec: Mapping, path: str = "$") -> dict:
    """Keep only the spec's keys, recursively. A missing key stays missing. A True leaf must be a JSON scalar or
    null, a dict leaf an object or null and a [subspec] leaf a list or null whose elements are pruned; any other
    value is CorpusStop(kind='row'). Non-allowlisted keys are never read."""
    if not isinstance(row, dict):
        raise CorpusStop(f"{path}: expected an object, got {type(row).__name__}", None, STOP_ROW)
    out = {}
    for key, sub in spec.items():
        if key in row:
            out[key] = _prune_value(row[key], sub, f"{path}.{key}")
    return out


