def leak_audit_train(X: np.ndarray, y: np.ndarray) -> LeakResult:
    """audit_target_leakage.py:60-96 applied to the outer-train matrix only: a feature column flags `exact` when it
    equals y, and `affine` when the least-squares affine fit of y on it has relative RMSE <= 1e-10 (columns or
    targets with zero SD skip the affine check). Columns with a non-finite value never flag; they are counted."""
    X = np.asarray(X, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)
    if X.ndim != 2 or y.ndim != 1 or X.shape[0] != y.shape[0]:
        raise ValueError("leak_audit_train needs X[n, p] and y[n]")
    exact: list[int] = []
    affine: list[tuple[int, float]] = []
    nonfinite = 0
    with np.errstate(all="ignore"):
        target_sd = float(np.std(y))
        for f in range(X.shape[1]):
            values = X[:, f]
            if not bool(np.all(np.isfinite(values))):
                nonfinite += 1      # the port could not flag it either: NaN/inf never equal a finite y, and its SD is NaN
                continue
            feature_sd = float(np.std(values))
            if np.array_equal(values, y):
                exact.append(f)
            if feature_sd <= 0 or target_sd <= 0:
                continue
            slope = float(np.cov(values, y, ddof=0)[0, 1] / (feature_sd * feature_sd))
            intercept = float(np.mean(y) - slope * np.mean(values))
            relative_rmse = float(np.sqrt(np.mean((y - (slope * values + intercept)) ** 2)) / target_sd)
            if relative_rmse <= LEAK_REL_RMSE:
                affine.append((f, relative_rmse))
    return LeakResult(tuple(exact), tuple(affine), nonfinite, bool(exact or affine))


def load_tokenizer(tok_dir: Path | str) -> tuple[dsl_tokenizer.Vocab, int, dict, dict]:
    """(vocab, max_seq, input_closure, pins) through dsl_tokenizer._load_tok; vocab.size <= 65,536 and
    max_seq <= 512 or STOP(tokenizer)."""
    tok_dir = Path(tok_dir)
    try:
        vocab, max_seq, closure = dsl_tokenizer._load_tok(tok_dir)
    except (OSError, ValueError, dsl_tokenizer.TokenizerStop) as err:
        raise CorpusStop(f"tokenizer {tok_dir}: {err}", None, STOP_TOKENIZER) from None
    if vocab.size > TOKEN_ID_LIMIT:
        raise CorpusStop(f"vocab.size {vocab.size} > {TOKEN_ID_LIMIT}", None, STOP_TOKENIZER)
    if not 2 <= max_seq <= MAX_SEQ_CAP:
        raise CorpusStop(f"max_seq {max_seq} outside 2..{MAX_SEQ_CAP}", None, STOP_TOKENIZER)
    pins = {"vocab_sha256": vocab.sha256, "vocab_size": vocab.size, "max_seq": max_seq,
            "vocab_json_sha256": common.sha256_file(tok_dir / "vocab.json"),
            "lengths_json_sha256": common.sha256_file(tok_dir / "lengths.json")}
    return vocab, max_seq, dict(closure), pins


