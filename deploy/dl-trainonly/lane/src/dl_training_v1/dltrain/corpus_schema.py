# ------------------------------------------------------------------------------------- 2.5 packed-history lines

PACKED_KINDS = ("manifest", "program", "outcome", "native", "transport", "summary")


def _summary_value(s: Any, key: str) -> int:
    v = s.get(key) if isinstance(s, Mapping) else getattr(s, key)
    if not _is_int(v) or v < 0:
        raise ValueError(f"summary {key} must be a non-negative integer")
    return v


def packed_line(kind: str, idx0: int, s: Any) -> int:
    """0-based line index in the decompressed packed history (pack_fold_history.build_history v1): line 0 is the
    manifest, then U program lines, outcome line i at 1+U+i, native line k at 1+U+O+k, transport line t at
    1+U+O+N+t, and the summary last. U, O, N, T are unique_programs, outcome_events, native_events and
    transport_events. Derived, never verified against S3 (history GETs are not allowed in this lane)."""
    U, O, N, T = (_summary_value(s, k) for k in ("unique_programs", "outcome_events", "native_events",
                                                 "transport_events"))
    if not _is_int(idx0) or idx0 < 0:
        raise ValueError("idx0 must be a non-negative integer")
    if kind == "manifest" and idx0 == 0:
        return 0
    if kind == "summary" and idx0 == 0:
        return 1 + U + O + N + T
    bounds = {"program": (1, U), "outcome": (1 + U, O), "native": (1 + U + O, N), "transport": (1 + U + O + N, T)}
    if kind not in bounds or idx0 >= bounds[kind][1]:
        raise ValueError(f"no {kind} line {idx0} in this layout")
    return bounds[kind][0] + idx0


# ----------------------------------------------------------------------------------- 2.6 outcome classification

def _native_class(native: NativeRow) -> str:
    if native.status == "abandoned":
        return f"abandoned:{native.reason}"
    return STATUS_CLASS[native.status]


def _native_agrees(native: NativeRow, evo: OutcomeRow) -> bool:
    if native.status == "abandoned":
        return evo.record_status == "missing" and evo.transport_status == native.reason
    return evo.record_status == native.status


def classify_outcome(origin: str | None, native: NativeRow | None, evo: OutcomeRow | None, boot: OutcomeRow | None,
                     counts: Counter | dict | None = None) -> str:
    """The outcome class before labels.normalize_outcome (PLAN §5 P5 Outcome classes; spec §2.6).

    evolution (a native row exists): completed|failed:unclassified|timeout@90000ms|abandoned:<reason>, and the last
    evolution outcome row must agree (abandoned(r) <-> record_status missing with transport_status r), else
    STOP(native_outcome_disagreement). Without one, the native row alone decides (counted native_without_outcome).
    bootstrap: the last bootstrap row; missing with an abandon-reason transport_status is abandoned:<reason>.
    transport_only: missing. An evolution outcome row for a program without a native row is STOP(outcome_not_native)."""
    if origin != "evolution" and evo is not None:
        raise CorpusStop(f"an evolution outcome row (line {evo.line_no}) names program {evo.program_sha256[:16]}, which "
                         f"has no native row", None, STOP_NOT_NATIVE)
    if origin == "evolution":
        if native is None:
            raise CorpusStop("evolution origin without a native row", None, STOP_ROW)
        cls = _native_class(native)
        if evo is None:
            _count(counts, "native_without_outcome")
            return cls
        if not _native_agrees(native, evo):
            raise CorpusStop(f"native line {native.line_no} ({cls}) disagrees with outcome line {evo.line_no} "
                             f"({evo.record_status}/{evo.transport_status})", None, STOP_DISAGREE)
        return cls
    if native is not None:
        raise CorpusStop(f"origin {origin!r} with a native row", None, STOP_ROW)
    if origin == "bootstrap":
        if boot is None:
            raise CorpusStop("bootstrap origin without a bootstrap row", None, STOP_ROW)
        if boot.record_status == "missing":
            return f"abandoned:{boot.transport_status}" if boot.transport_status in ABANDON_REASONS else MISSING
        if boot.record_status not in STATUS_CLASS:
            raise CorpusStop(f"bootstrap record_status {boot.record_status!r}", None, STOP_ROW)
        return STATUS_CLASS[boot.record_status]
    if origin == "transport_only":
        if boot is not None:
            raise CorpusStop("transport_only origin with a bootstrap row", None, STOP_ROW)
        return MISSING
    raise CorpusStop(f"program has no native, bootstrap or transport row with a program (origin {origin!r})", None,
                     STOP_ROW)


