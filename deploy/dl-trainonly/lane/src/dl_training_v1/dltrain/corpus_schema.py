def backend_class(s: Any) -> str:
    """local for xbabe nodes and pools; aws_lambda for aws, aws:<region>, aws:<region>:<function> and the region-less
    aws:<function> (the attempt node prefix decides, PLAN §5 P5); else unknown (fullmatch)."""
    if isinstance(s, str):
        if LOCAL_NODE_RE.fullmatch(s):
            return "local"
        if AWS_NODE_RE.fullmatch(s):
            return "aws_lambda"
    return "unknown"


@dataclass(frozen=True)
class BackendInfo:
    backend: str
    source: str
    raw: str | None = None
    unknown_prefix: str | None = None


def _info(raw: str | None, source: str) -> BackendInfo:
    cls = backend_class(raw)
    prefix = raw[:UNKNOWN_PREFIX_CHARS] if cls == "unknown" and isinstance(raw, str) else None
    return BackendInfo(cls, source, raw, prefix)


def index_attempts(rows: Iterable[TransportRow]) -> tuple[dict[str, TransportRow], int]:
    """attempt_id -> transport row of one context (the last row wins) and the number of duplicate attempt_ids."""
    index: dict[str, TransportRow] = {}
    dups = 0
    for r in rows:
        if r.attempt_id is None:
            continue
        if r.attempt_id in index:
            dups += 1
        index[r.attempt_id] = r
    return index, dups


@dataclass
class ProgramAcc:
    """Everything one context's sources say about one program: the native row, the last evolution and the last
    bootstrap outcome rows (bootstrap rows that carry a program, as in P4a), its transport rows and counts."""
    program_sha256: str
    native: NativeRow | None = None
    evo: OutcomeRow | None = None
    boot: OutcomeRow | None = None
    attempts: list = field(default_factory=list)
    counts: Counter = field(default_factory=Counter)
    transport_dsl: str | None = None

    def _own(self, row) -> None:
        if row.program_sha256 != self.program_sha256:
            raise ValueError("row of another program")

    def add_native(self, row: NativeRow) -> None:
        self._own(row)
        if self.native is not None:
            raise CorpusStop(f"duplicate native program at lines {self.native.line_no} and {row.line_no}", None,
                             STOP_ROW)
        self.native = row
        self.counts["native_rows"] += 1

    def add_outcome(self, row: OutcomeRow) -> None:
        self._own(row)
        if row.phase == "evolution":
            if self.evo is not None:
                self.counts["evolution_outcome_duplicates"] += 1
            self.evo = row
            self.counts["evolution_outcome_rows"] += 1
        elif row.dsl is None:
            self.counts["bootstrap_rows_without_program"] += 1
        else:
            self.boot = row
            self.counts["bootstrap_events"] += 1

    def add_transport(self, row: TransportRow) -> None:
        self._own(row)
        if self.transport_dsl is None and row.dsl is not None:
            self.transport_dsl = row.dsl
        self.attempts.append(row)
        self.counts["transport_attempts"] += 1

    @property
    def origin(self) -> str | None:
        if self.native is not None:
            return "evolution"
        if self.boot is not None:
            return "bootstrap"
        if self.transport_dsl is not None:
            return "transport_only"
        return None

    @property
    def dsl(self) -> str | None:
        """native program.dsl, else the last bootstrap program.dsl, else the first transport program.dsl."""
        if self.native is not None:
            return self.native.dsl
        if self.boot is not None:
            return self.boot.dsl
        return self.transport_dsl

    @property
    def metrics(self) -> OutcomeRow | None:
        """The metrics outcome row: the last evolution row for evolution origin, the last bootstrap row for
        bootstrap origin, none for transport_only."""
        origin = self.origin
        if origin == "evolution":
            return self.evo
        if origin == "bootstrap":
            return self.boot
        return None


def accumulate_programs(native: Iterable[NativeRow], outcomes: Iterable[OutcomeRow],
                        transports: Iterable[TransportRow]) -> tuple[dict[str, ProgramAcc], dict[str, TransportRow], int]:
    """ProgramAcc per program_sha256 (rows in line order), the context's attempt index and its duplicate count."""
    accs: dict[str, ProgramAcc] = {}

    def acc(sha: str) -> ProgramAcc:
        a = accs.get(sha)
        if a is None:
            a = accs[sha] = ProgramAcc(sha)
        return a

    for r in native:
        acc(r.program_sha256).add_native(r)
    for r in outcomes:
        acc(r.program_sha256).add_outcome(r)
    tlist = list(transports)
    for r in tlist:
        if r.program_sha256 is not None:
            acc(r.program_sha256).add_transport(r)
    index, dups = index_attempts(tlist)
    return accs, index, dups


def derive_backend(prog: ProgramAcc, attempt_index: Mapping[str, TransportRow] | None = None) -> BackendInfo:
    """The backend class of a program (spec §2.7), in order: (1) the metrics outcome row's node; (2) else the
    transport row whose attempt_id equals that row's attempt_id (context attempt index, else the program's own
    transport rows, last wins): its pool; (3) else, for a transport_only program, the class all of its transport
    pools share; (4) else unknown. The row's own backend string and prepared.json execution_backend are never used."""
    m = prog.metrics
    if m is not None and m.node:
        return _info(m.node, "outcome_node")
    if m is not None and m.attempt_id is not None:
        t = None
        if attempt_index is not None:
            t = attempt_index.get(m.attempt_id)
        else:
            for row in prog.attempts:
                if row.attempt_id == m.attempt_id:
                    t = row
        if t is not None and t.pool:
            return _info(t.pool, "transport_attempt")
    if prog.origin == "transport_only":
        pools = [t.pool for t in prog.attempts]
        if pools and all(isinstance(p, str) and p for p in pools):
            classes = {backend_class(p) for p in pools}
            if len(classes) == 1:
                return _info(pools[0], "transport_unanimous")
    return BackendInfo("unknown", "none")


