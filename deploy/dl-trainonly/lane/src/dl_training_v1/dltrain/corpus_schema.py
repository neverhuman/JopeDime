class CorpusStop(RuntimeError):
    """A P5 STOP (PLAN §5 P5 Failure). `kind` names the rule and `context` the context_sha256, when one applies.

    The argument order follows programs.ReconcileError: (message, context, kind)."""

    def __init__(self, message: str = "", context: str | None = None, kind: str = "stop"):
        where = f"[{context[:16]}] " if isinstance(context, str) and context else ""
        super().__init__(f"{kind}: {where}{message}")
        self.kind = kind
        self.context = context
        self.detail = message


