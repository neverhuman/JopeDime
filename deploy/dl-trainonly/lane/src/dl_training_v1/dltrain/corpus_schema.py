def project_official_test_exposed(block: Any, counts: Counter | None = None) -> dict:
    """evaluation_detail.official_test flattened to the official_test_* columns; unmapped keys are counted."""
    types = {f.name: f.type for f in EXPOSED_RECORD_SCHEMA if f.name.startswith("official_test_")}
    out = dict.fromkeys(types)
    if block is None:
        return out
    if not isinstance(block, Mapping):
        _count(counts, X_BAD_TYPE)
        return out
    groups = ("metrics", "baseline_metrics", "training_metrics")
    scalars = ("train_rows", "score_rows", "wall_us", "started_utc_us", "fit_finished_utc_us", "finished_utc_us",
               "index", "model_sha256", "kind", "schema", "serialized_prediction_replay_exact")
    unmapped = 0
    for key, value in block.items():
        if key in groups:
            if value is None:
                continue
            if not isinstance(value, Mapping):
                _count(counts, X_BAD_TYPE)
                continue
            for mkey, mval in value.items():
                col = f"official_test_{key}_{mkey}"
                if col in types:
                    out[col] = _x_typed(mval, types[col], counts)
                else:
                    unmapped += 1
        elif key in scalars:
            col = f"official_test_{key}"
            out[col] = _x_typed(value, types[col], counts)
        else:
            unmapped += 1
    _count(counts, X_UNMAPPED, unmapped)
    return out


