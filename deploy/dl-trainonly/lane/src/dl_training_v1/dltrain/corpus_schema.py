def _same(a: Any, b: Any) -> bool:
    """Exact agreement, with NaN equal to NaN and None only equal to None."""
    if a is None or b is None:
        return a is None and b is None
    if isinstance(a, bool) or isinstance(b, bool):
        return isinstance(a, bool) and isinstance(b, bool) and a == b
    if isinstance(a, float) and isinstance(b, float) and math.isnan(a) and math.isnan(b):
        return True
    return a == b


def f64_hex(x: float) -> str:
    """The IEEE-754 binary64 bits of x, big-endian hex (16 characters)."""
    return struct.pack(">d", float(x)).hex()


def ulp_distance(a: Any, b: Any) -> int | None:
    """|bits(a) - bits(b)| as int64 for two finite floats of the same sign (+0.0 and -0.0 are one value); None for
    anything else (None, NaN, an infinity, opposite signs)."""
    if not (isinstance(a, float) and isinstance(b, float)) or not (math.isfinite(a) and math.isfinite(b)):
        return None
    if a == b:
        return 0
    a, b = a + 0.0, b + 0.0                   # -0.0 -> +0.0
    if (a < 0.0) != (b < 0.0):
        return None
    ia = struct.unpack("<q", struct.pack("<d", a))[0]
    ib = struct.unpack("<q", struct.pack("<d", b))[0]
    return abs(ia - ib)


def canonical_cv_log_ratio_sd(rmse_j: Any, baseline_rmse_j: Any) -> float | None:
    """The lane's one implementation of the inner-CV log-ratio SD (CV_SD_POLICY): with float64 values and a fixed
    operation order, l_j = log(rmse_j / baseline_rmse_j) for j = 0, 1; m = (l_0 + l_1) / 2;
    v = ((l_0 - m) * (l_0 - m) + (l_1 - m) * (l_1 - m)) / 2; sd = math.sqrt(v) (correctly rounded). None unless both
    pairs hold INNER_FOLDS real values that are finite and > 0 with a finite ratio > 0 (the value is then not computed
    by P5 and the writer's own value is stored verbatim)."""
    if not isinstance(rmse_j, (list, tuple)) or not isinstance(baseline_rmse_j, (list, tuple)):
        return None
    if len(rmse_j) != INNER_FOLDS or len(baseline_rmse_j) != INNER_FOLDS:
        return None
    logs = []
    for r, b in zip(rmse_j, baseline_rmse_j):
        if not (_is_real(r) and _is_real(b)):
            return None
        r, b = float(r), float(b)
        if not (math.isfinite(r) and math.isfinite(b) and r > 0.0 and b > 0.0):
            return None
        ratio = r / b
        if not (math.isfinite(ratio) and ratio > 0.0):
            return None
        logs.append(math.log(ratio))
    l0, l1 = logs
    m = (l0 + l1) / 2.0
    d0, d1 = l0 - m, l1 - m
    return math.sqrt((d0 * d0 + d1 * d1) / 2.0)


def _check_cv_agreement(native: NativeRow, evo: OutcomeRow, cid: str) -> dict | None:
    """Native vs evolution-outcome cv values: cv_mean_log_ratio and cv_gate_passed must agree exactly; cv_log_ratio_sd
    exactly or within CV_SD_MAX_ULPS (both finite, same sign). Returns the tolerated hit {field, program_sha256,
    native_line, outcome_line, native_bits, outcome_bits, ulps}, or None; any other difference is
    STOP(native_outcome_disagreement)."""
    hit = None
    for key in (CV_EXACT_FIELDS[0], CV_SD_FIELD, CV_EXACT_FIELDS[1]):
        a, b = getattr(native, key), getattr(evo, key)
        if _same(a, b):
            continue
        if key == CV_SD_FIELD:
            u = ulp_distance(a, b)
            if u is not None and u <= CV_SD_MAX_ULPS:
                hit = {"field": key, "program_sha256": native.program_sha256, "native_line": native.line_no,
                       "outcome_line": evo.line_no, "native_bits": f64_hex(a), "outcome_bits": f64_hex(b), "ulps": u}
                continue
        raise CorpusStop(f"{key} differs between native line {native.line_no} and outcome line {evo.line_no}",
                         cid, STOP_DISAGREE)
    return hit


def check_evaluation_reuse(rows: Iterable[OutcomeRow], *, cid: str, raw_sha256: str, header: Mapping,
                           split_role: str | None = None, role_of: Mapping[str, str] | None = None) -> dict:
    """Every outcome row that carries evaluation_reuse (red-team LA-9): schema REUSE_SCHEMA, a 64-hex source context,
    compatibility_identity.input_raw_sha256 == this context's raw JTT1 sha256 (the whole input, its shape included),
    evaluator_sha256 == EVALUATOR_SHA256, candidate_timeout_ms == 90000, train_rows == n_train and
    encoded_features == p; and a source context that the partition map knows must hold this context's split_role.
    Anything else is STOP(evaluation_reuse). Returns {rows, foreign} counts."""
    counts = {"rows": 0, "foreign": 0}
    for r in rows:
        u = r.reuse
        if u is None:
            continue
        counts["rows"] += 1
        where = f"outcome line {r.line_no}: evaluation_reuse"
        checks = (
            (u.schema == REUSE_SCHEMA, f"schema {u.schema!r} != {REUSE_SCHEMA}"),
            (programs._is_hex64(u.source_context_sha256), "source_context_sha256 is not 64-hex"),
            (u.input_raw_sha256 == raw_sha256, "input_raw_sha256 is not this context's JTT1 input"),
            (u.evaluator_sha256 == EVALUATOR_SHA256, "evaluator_sha256 differs from the pin"),
            (_is_int(u.candidate_timeout_ms) and u.candidate_timeout_ms == TIMEOUT_MS, f"candidate_timeout_ms != {TIMEOUT_MS}"),
            (_is_int(u.train_rows) and u.train_rows == header["n_train"], "train_rows != the JTT1 n_train"),
            (_is_int(u.encoded_features) and u.encoded_features == header["p"], "encoded_features != the JTT1 p"),
        )
        for ok, msg in checks:
            if not ok:
                raise CorpusStop(f"{where}: {msg}", cid, STOP_REUSE)
        if u.source_context_sha256 != cid:
            counts["foreign"] += 1
            other = (role_of or {}).get(u.source_context_sha256)
            if other is not None and split_role is not None and other != split_role:
                raise CorpusStop(f"{where}: the source context is mapped to {other}, not {split_role}", cid, STOP_REUSE)
    return counts


def _detail_ratio(rec: Mapping) -> float | None:
    if not labels.is_detailed(rec):
        return None
    r, b = rec["rmse_j"], rec["baseline_rmse_j"]
    if not all(x > 0 for x in b):
        return None
    return 0.5 * (r[0] / b[0] + r[1] / b[1])


@dataclass
class ContextRecords:
    """build_context_records output: kept TRAIN_RECORD_SCHEMA rows and refused rows (both sha-sorted), the labels,
    per-program outcome and backend, and the context counts for its ctx-record."""
    records: list
    refused: list
    context_label: labels.ContextLabel
    record_labels: tuple
    outcomes: dict
    backends: dict
    counts: dict


def _meta(ctx_meta: Any, key: str) -> Any:
    """A required ctx_meta value; a missing one (e.g. an epoch entry without context_schema) is STOP(input)."""
    def get(k):
        return ctx_meta.get(k) if isinstance(ctx_meta, Mapping) else getattr(ctx_meta, k, None)
    v = get(key)
    if v is None:
        cid = get("context_sha256")
        raise CorpusStop(f"context metadata lacks {key}", cid if isinstance(cid, str) else None, STOP_INPUT)
    return v


def build_context_records(ctx_meta: Any, programs_acc: Mapping[str, ProgramAcc] | Iterable[ProgramAcc], vocab: Any,
                          max_seq: int, seeds: Iterable[str], *,
                          attempt_index: Mapping[str, TransportRow] | None = None) -> ContextRecords:
    """TRAIN_RECORD_SCHEMA rows of one context, in program_sha256 order, joined with labels.label_context.

    ctx_meta: context_sha256, context_schema, dataset_hash, family_id, split_role and y_train (outer-train targets).
    Per program: the dsl (native, else the last bootstrap row, else the first transport row) is tokenized (RAW is
    STOP raw_program); metrics come from the metrics outcome row (cv values fall back to the native row only when
    there is none); native and outcome cv values must agree exactly except cv_log_ratio_sd, which may differ by at
    most CV_SD_MAX_ULPS (each hit counted and listed, else STOP native_outcome_disagreement). The stored
    cv_log_ratio_sd is canonical_cv_log_ratio_sd of the stored rmse_j/baseline_rmse_j when computable (it must lie
    within CV_SD_MAX_ULPS of every finite writer value, else STOP cv_sd_recompute), else the writer's own value. The
    outcome is classify_outcome then labels.normalize_outcome; length > max_seq is STOP(max_seq) for train_fit and
    a refused row otherwise. gate_pass is RecordLabel.gate_pass; the evaluator's cv_gate_passed must equal it
    except within GATE_TIE_EPS of 1.05 (gate_boundary_ties), else STOP(gate_drift)."""
    cid = _meta(ctx_meta, "context_sha256")
    role = _meta(ctx_meta, "split_role")
    if role not in PARTITIONS:
        raise CorpusStop(f"split_role {role!r} is not a partition", cid, STOP_ROW)
    context_schema, dataset_hash = _meta(ctx_meta, "context_schema"), _meta(ctx_meta, "dataset_hash")
    family_id, y_train = _meta(ctx_meta, "family_id"), _meta(ctx_meta, "y_train")
    seed_set = frozenset(seeds)
    if isinstance(programs_acc, Mapping):
        accs = dict(programs_acc)
    else:
        accs = {}
        for a in programs_acc:
            if a.program_sha256 in accs:
                raise ValueError("duplicate ProgramAcc")
            accs[a.program_sha256] = a
    counts: Counter = Counter()
    kept, refused, verdicts = [], [], {}
    outcomes: dict[str, str] = {}
    backends: dict[str, BackendInfo] = {}
    unknown_prefixes: Counter = Counter()
    sd_ties: list[dict] = []
    for sha in sorted(accs):
        acc = accs[sha]
        if acc.program_sha256 != sha:
            raise ValueError("ProgramAcc keyed under another program_sha256")
        origin = acc.origin
        try:
            cls = classify_outcome(origin, acc.native, acc.evo, acc.boot, counts)
        except CorpusStop as err:
            raise CorpusStop(f"program {sha[:16]}: {err.detail}", cid, err.kind) from None
        dsl = acc.dsl
        if dsl is None:
            raise CorpusStop(f"program {sha[:16]} has no dsl source", cid, STOP_ROW)
        ids = dsl_tokenizer.tokenize(dsl, vocab)
        if ids[1] == dsl_tokenizer.RAW_BEGIN:
            raise CorpusStop(f"program {sha[:16]} matches no form (RAW)", cid, STOP_RAW)
        if max(ids) >= TOKEN_ID_LIMIT:
            raise CorpusStop(f"program {sha[:16]} has a token id >= {TOKEN_ID_LIMIT}", cid, STOP_TOKEN_ID)
        nat, m = acc.native, acc.metrics
        if nat is not None and acc.evo is not None:
            hit = _check_cv_agreement(nat, acc.evo, cid)
            if hit is not None:
                sd_ties.append(hit)
        if m is not None:
            cvm, cvsd, ratio, wall = m.cv_mean_log_ratio, m.cv_log_ratio_sd, m.cv_mean_rmse_ratio, m.wall_us
            rmse_j = None if m.rmse_j is None else list(m.rmse_j)
            base_j = None if m.baseline_rmse_j is None else list(m.baseline_rmse_j)
            verdict = m.cv_gate_passed
        else:
            cvm = nat.cv_mean_log_ratio if nat is not None else None
            cvsd = nat.cv_log_ratio_sd if nat is not None else None
            ratio = wall = rmse_j = base_j = None
            verdict = nat.cv_gate_passed if nat is not None else None
        canon = canonical_cv_log_ratio_sd(rmse_j, base_j)
        if canon is None:
            counts["cv_sd_verbatim"] += cvsd is not None
        else:
            writers = [("outcome", m.cv_log_ratio_sd)]
            if nat is not None and m is acc.evo:
                writers.append(("native", nat.cv_log_ratio_sd))
            for who, w in writers:
                if not isinstance(w, float) or not math.isfinite(w):
                    counts["cv_sd_writer_nonfinite"] += 1
                    continue
                u = ulp_distance(canon, w)
                if u is None or u > CV_SD_MAX_ULPS:
                    raise CorpusStop(f"program {sha[:16]}: canonical {CV_SD_FIELD} {canon!r} is more than "
                                     f"{CV_SD_MAX_ULPS} ULP from the {who} writer's {w!r}", cid, STOP_CV_SD)
                counts["cv_sd_canonical_ulp"] += u > 0
            cvsd = canon
            counts["cv_sd_canonical"] += 1
        b = derive_backend(acc, attempt_index)
        rec = {"context_sha256": cid, "context_schema": context_schema, "dataset_hash": dataset_hash,
               "family_id": family_id, "split_role": role, "program_sha256": sha,
               "skeleton_sha256": dsl_tokenizer.skeleton_sha256(dsl), "tokens": ids, "length": len(ids),
               "outcome": cls, "rmse_j": rmse_j, "baseline_rmse_j": base_j, "cv_mean_log_ratio": cvm,
               "cv_log_ratio_sd": cvsd, "cv_mean_ratio": ratio, "gate_pass": None, "wall_us": wall,
               "backend": b.backend, "shared_seed": sha in seed_set}
        try:
            rec["outcome"] = labels.normalize_outcome(rec)
        except labels.LabelError as err:
            raise CorpusStop(f"program {sha[:16]}: {err}", cid, STOP_LABEL) from None
        outcomes[sha], backends[sha] = rec["outcome"], b
        counts["backend_source:" + b.source] += 1
        if b.unknown_prefix is not None:
            unknown_prefixes[b.unknown_prefix] += 1
        if len(ids) > max_seq:
            if role == "train_fit":
                raise CorpusStop(f"train_fit program {sha[:16]} has {len(ids)} tokens > max_seq {max_seq}", cid,
                                 STOP_MAX_SEQ)
            refused.append({"context_sha256": cid, "program_sha256": sha, "split_role": role, "length": len(ids),
                            "reason": REFUSED_REASONS[0]})
            counts["refused_outcome:" + rec["outcome"]] += 1
            continue
        verdicts[sha] = verdict
        kept.append(rec)
    ctx_row = {"context_sha256": cid, "family_id": family_id, "dataset_hash": dataset_hash, "split_role": role,
               "y_train": y_train}
    try:
        ctx_label, rec_labels = labels.label_context(ctx_row, kept)
    except labels.LabelError as err:
        raise CorpusStop(str(err), cid, STOP_LABEL) from None
    by_sha = {lab.program_sha256: lab for lab in rec_labels}
    for rec in kept:
        sha = rec["program_sha256"]
        lab = by_sha[sha]
        if lab.outcome != rec["outcome"]:
            raise CorpusStop(f"program {sha[:16]}: stored outcome {rec['outcome']} != labels {lab.outcome}", cid,
                             STOP_LABEL)
        rec["gate_pass"] = lab.gate_pass
        verdict = verdicts[sha]
        if rec["outcome"] == COMPLETED:
            if lab.gate_pass is None or verdict is None:
                if lab.gate_pass is not verdict:
                    counts["gate_unverified"] += 1
            elif lab.gate_pass != verdict:
                r = rec["cv_mean_ratio"] if rec["cv_mean_ratio"] is not None else _detail_ratio(rec)
                if r is not None and abs(r - GATE_RATIO) <= GATE_TIE_EPS:
                    counts["gate_boundary_ties"] += 1
                else:
                    raise CorpusStop(f"program {sha[:16]}: evaluator cv_gate_passed {verdict} != labels gate_pass "
                                     f"{lab.gate_pass} (ratio {r})", cid, STOP_GATE)
            if labels.is_detailed(rec):
                counts["detailed_completed"] += 1
            else:
                counts["detailless_completed"] += 1
    by_outcome = Counter(rec["outcome"] for rec in kept)
    by_backend = Counter(rec["backend"] for rec in kept)
    summary = {
        "records": len(kept),
        "refused": len(refused),
        "by_outcome": dict(sorted(by_outcome.items())),
        "by_backend": dict(sorted(by_backend.items())),
        "backend_source": {k.split(":", 1)[1]: v for k, v in sorted(counts.items()) if k.startswith("backend_source:")},
        "refused_by_outcome": {k.split(":", 1)[1]: v for k, v in sorted(counts.items())
                               if k.startswith("refused_outcome:")},
        "native_without_outcome": counts["native_without_outcome"],
        "evolution_outcome_duplicates": sum(a.counts["evolution_outcome_duplicates"] for a in accs.values()),
        "bootstrap_rows_without_program": sum(a.counts["bootstrap_rows_without_program"] for a in accs.values()),
        "detailed_completed": counts["detailed_completed"],
        "detailless_completed": counts["detailless_completed"],
        "gate_boundary_ties": counts["gate_boundary_ties"],
        "gate_unverified": counts["gate_unverified"],
        "unknown_backend_prefixes": dict(sorted(unknown_prefixes.items())),
        "cv_sd_ulp_ties": len(sd_ties),
        "cv_sd_ulp_tie_items": sorted(sd_ties, key=lambda h: h["program_sha256"]),
        "cv_sd_canonical": counts["cv_sd_canonical"],
        "cv_sd_canonical_ulp": counts["cv_sd_canonical_ulp"],
        "cv_sd_verbatim": counts["cv_sd_verbatim"],
        "cv_sd_writer_nonfinite": counts["cv_sd_writer_nonfinite"],
    }
    return ContextRecords(records=kept, refused=refused, context_label=ctx_label, record_labels=rec_labels,
                          outcomes=outcomes, backends=backends, counts=summary)


def build_context_row(ctx_meta: Any, train: TrainInput, ctx_label: labels.ContextLabel, n_records: int,
                      n_refused: int) -> dict:
    """One TRAIN_CONTEXT_SCHEMA row. ctx_meta adds cohort, fold, context_schema and the epoch eligibility_source
    text; s_c and eps_c must equal labels' recomputation over the same y_train."""
    cid = _meta(ctx_meta, "context_sha256")
    if ctx_label.context_sha256 != cid:
        raise ValueError("ContextLabel of another context")
    if ctx_label.s_c != train.s_c or ctx_label.eps_c != train.eps_c:
        raise CorpusStop("labels s_c/eps_c differ from the JTT1 train input", cid, STOP_LABEL)
    cohort, fold = _meta(ctx_meta, "cohort"), _meta(ctx_meta, "fold")
    return {"context_sha256": cid, "context_schema": _meta(ctx_meta, "context_schema"),
            "dataset_hash": _meta(ctx_meta, "dataset_hash"), "family_id": _meta(ctx_meta, "family_id"),
            "split_role": _meta(ctx_meta, "split_role"), "cohort": cohort, "fold": fold,
            "frozen_fold0": cohort == "frozen" and fold == 0, "n_train": train.n_train, "n_features": train.p,
            "inner_folds": train.inner_folds, "y_train": [float(v) for v in train.y.tolist()],
            "train_rows_sha256": train.train_rows_sha256, "s_c": ctx_label.s_c, "eps_c": ctx_label.eps_c,
            "label_status": ctx_label.status,
            "baseline_rmse_j": None if ctx_label.baseline_rmse_j is None else list(ctx_label.baseline_rmse_j),
            "q_cap": ctx_label.q_cap, "n_records": int(n_records), "n_refused": int(n_refused),
            "eligibility_source": str(_meta(ctx_meta, "eligibility_source")) + LEAK_PASS_SUFFIX}


