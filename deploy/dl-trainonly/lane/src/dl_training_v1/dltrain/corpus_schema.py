def _table_lookup(table: Any) -> tuple[str, pa.Schema]:
    if isinstance(table, pa.Schema):
        for tid, s in TABLES.items():
            if s is table or s.equals(table):
                return tid, s
        raise KeyError("not a P5 table schema")
    tid = TABLE_SHORT.get(table, table)
    if tid not in TABLES:
        for full in TABLES:
            if full.split("/")[0].endswith("-" + str(table)):
                return full, TABLES[full]
        raise KeyError(f"unknown P5 table {table!r}")
    return tid, TABLES[tid]


# --------------------------------------------------------------------------------------------- 2.3 JSON Schemas

_INT_RANGE = {"int8": (-2**7, 2**7 - 1), "int16": (-2**15, 2**15 - 1), "int32": (-2**31, 2**31 - 1),
              "int64": (-2**63, 2**63 - 1), "uint16": (0, 2**16 - 1)}


def _json_scalar(typ: pa.DataType, name: str, nullable: bool) -> dict:
    if pa.types.is_string(typ):
        d: dict = {"type": "string"}
        if name.endswith("sha256"):
            d["pattern"] = "^[0-9a-f]{64}$"
        if name == "outcome":
            d["pattern"] = OUTCOME_PATTERN
        if name in _ENUMS:
            d["enum"] = list(_ENUMS[name])
    elif pa.types.is_boolean(typ):
        d = {"type": "boolean"}
    elif pa.types.is_integer(typ):
        lo, hi = _INT_RANGE[str(typ)]
        d = {"type": "integer", "minimum": lo, "maximum": hi}
    elif pa.types.is_floating(typ):
        d = {"type": "number"}
    else:
        raise TypeError(f"column {name}: type {typ} has no JSON Schema rule")
    if nullable:
        d["type"] = [d["type"], "null"]
        if "enum" in d:
            d["enum"] = [*d["enum"], None]
    return d


def _json_prop(table_id: str, f: pa.Field) -> dict:
    if pa.types.is_list(f.type):
        d: dict = {"type": ["array", "null"] if f.nullable else "array",
                   "items": _json_scalar(f.type.value_type, f.name + "[]", f.name not in _ITEMS_NOT_NULL)}
        if f.name in _PAIR_LISTS:
            d.update(minItems=2, maxItems=2)
    else:
        d = _json_scalar(f.type, f.name, f.nullable)
    d.update(_JSON_EXTRA.get((table_id, f.name), {}))
    return d


def json_schema(table: Any) -> dict:
    """JSON Schema 2020-12 of one P5 table (by id, short name or Arrow schema): an object with additionalProperties
    false, every column required (nullable columns admit null), 64-hex sha columns, uint16 ranges, the outcome
    pattern, enums for enumerated columns and explicit array items."""
    tid, schema = _table_lookup(table)
    return {
        "$schema": JSON_SCHEMA_DIALECT,
        "$id": tid,
        "title": tid,
        "description": TABLE_DESCRIPTIONS[tid],
        "type": "object",
        "additionalProperties": False,
        "required": list(schema.names),
        "properties": {f.name: _json_prop(tid, f) for f in schema},
        "x-arrow-schema-sha256": schema_sha256(schema),
        "x-sealed": tid in SEALED_TABLES,
    }


def json_schema_bytes(table: Any) -> bytes:
    return common.canonical(json_schema(table)) + b"\n"


def schema_file(table: Any, root: Path | str = SCHEMAS_DIR) -> Path:
    tid, _ = _table_lookup(table)
    return Path(root) / f"{tid.split('/')[0]}.schema.json"


def write_json_schemas(root: Path | str = SCHEMAS_DIR) -> dict:
    """Write the five JSON Schema files (canonical JSON + newline); returns {path: sha256}."""
    out = {}
    for tid in TABLES:
        res = common.atomic_write(schema_file(tid, root), json_schema_bytes(tid))
        out[res["path"]] = res["sha256"]
    return out


def check_json_schemas(root: Path | str = SCHEMAS_DIR) -> list[str]:
    """Failures (empty when every checked-in file equals its generated bytes)."""
    fails = []
    for tid in TABLES:
        p = schema_file(tid, root)
        if not p.is_file():
            fails.append(f"{p}: missing")
        elif p.read_bytes() != json_schema_bytes(tid):
            fails.append(f"{p}: differs from the generated bytes")
    return fails


