def _is_real(v: Any) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _is_int(v: Any) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _opt_real(view: Mapping, key: str, where: str, ctx: str) -> float | None:
    v = view.get(key)
    if v is None:
        return None
    if not _is_real(v):
        raise CorpusStop(f"{where}: {key} must be a number or null", ctx, STOP_ROW)
    return float(v)


def _opt_bool(view: Mapping, key: str, where: str, ctx: str) -> bool | None:
    v = view.get(key)
    if v is None or isinstance(v, bool):
        return v
    raise CorpusStop(f"{where}: {key} must be a boolean or null", ctx, STOP_ROW)


def _opt_str(view: Mapping, key: str, where: str, ctx: str) -> str | None:
    v = view.get(key)
    if v is None or isinstance(v, str):
        return v
    raise CorpusStop(f"{where}: {key} must be a string or null", ctx, STOP_ROW)


def _opt_wall(view: Mapping, key: str, where: str, ctx: str) -> int | None:
    v = view.get(key)
    if v is None:
        return None
    if isinstance(v, float) and math.isfinite(v) and v == int(v):
        v = int(v)
    if not _is_int(v) or v < 0:
        raise CorpusStop(f"{where}: {key} must be a non-negative integer or null", ctx, STOP_ROW)
    return v


def _load_row(line: Any, where: str, ctx: str) -> dict:
    """One JSONL line, json.loads-ed once (NaN and Infinity tokens are accepted); a dict is taken as already parsed."""
    if isinstance(line, dict):
        return line
    try:
        full = json.loads(line)
    except (ValueError, TypeError) as err:
        raise CorpusStop(f"{where}: invalid JSON ({err})", ctx, STOP_SOURCE) from None
    if not isinstance(full, dict):
        raise CorpusStop(f"{where}: record is not a JSON object", ctx, STOP_SOURCE)
    return full


def _check_program(dsl: Any, sha: Any, where: str, ctx: str) -> None:
    try:
        programs._check_program(dsl, sha, where, ctx)
    except programs.ReconcileError as err:
        raise CorpusStop(str(err), ctx, err.kind) from None


def _view(full: dict, spec: Mapping, where: str, ctx: str) -> dict:
    try:
        return prune(full, spec, where)
    except CorpusStop as err:
        raise CorpusStop(err.detail, ctx, err.kind) from None


def parse_native(line: Any, line_no: int, ctx: Any) -> tuple[NativeRow, dict]:
    """(NativeRow, full row) of one native evaluation line. The NativeRow reads only the NATIVE_TRAIN_SPEC view."""
    c = ctx_identity(ctx)
    cid, where = c.context_sha256, f"native line {line_no}"
    full = _load_row(line, where, cid)
    v = _view(full, NATIVE_TRAIN_SPEC, where, cid)
    if v.get("context_sha256") != cid:
        raise CorpusStop(f"{where}: context_sha256 is not this context", cid, STOP_IDENTITY)
    prog = v.get("program")
    if not isinstance(prog, dict):
        raise CorpusStop(f"{where}: no program object", cid, STOP_ROW)
    dsl, sha = prog.get("dsl"), prog.get("program_sha256")
    _check_program(dsl, sha, where, cid)
    status, reason = v.get("status"), None
    if status == "abandoned":
        reason = v.get("reason")
        if reason not in ABANDON_REASONS:
            raise CorpusStop(f"{where}: abandon reason {reason!r} is outside {ABANDON_REASONS}", cid, STOP_ROW)
        if v.get("program_sha256") != sha:
            raise CorpusStop(f"{where}: abandonment program_sha256 differs from program.program_sha256", cid, STOP_ROW)
    elif status not in NATIVE_STATUSES:
        raise CorpusStop(f"{where}: status {status!r} is outside {NATIVE_STATUSES}", cid, STOP_ROW)
    elif v.get("program_sha256") is not None and v.get("program_sha256") != sha:
        raise CorpusStop(f"{where}: top-level program_sha256 differs from program.program_sha256", cid, STOP_ROW)
    row = NativeRow(line_no=line_no, program_sha256=sha, dsl=dsl, status=status, reason=reason,
                    cv_mean_log_ratio=_opt_real(v, "cv_mean_log_ratio", where, cid),
                    cv_log_ratio_sd=_opt_real(v, "cv_log_ratio_sd", where, cid),
                    cv_gate_passed=_opt_bool(v, "cv_gate_passed", where, cid))
    return row, full


def parse_outcome(line: Any, line_no: int, ctx: Any) -> tuple[OutcomeRow, dict]:
    """(OutcomeRow, full row) of one history-outcome (hwm-event) line, from the OUTCOME_TRAIN_SPEC view only.
    context_sha256, view_id, dataset_hash and outer_fold must equal the context's."""
    c = ctx_identity(ctx)
    if c.view_id is None or c.dataset_hash is None or c.fold is None:
        raise ValueError("parse_outcome needs the context's view_id, dataset_hash and fold")
    cid, where = c.context_sha256, f"outcome line {line_no}"
    full = _load_row(line, where, cid)
    v = _view(full, OUTCOME_TRAIN_SPEC, where, cid)
    fold = v.get("outer_fold")
    if (v.get("context_sha256"), v.get("view_id"), v.get("dataset_hash")) != (cid, c.view_id, c.dataset_hash) \
            or not _is_int(fold) or fold != c.fold:
        raise CorpusStop(f"{where}: context_sha256, view_id, dataset_hash or outer_fold is not this context's", cid,
                         STOP_IDENTITY)
    phase = v.get("phase")
    if phase not in OUTCOME_PHASES:
        raise CorpusStop(f"{where}: phase {phase!r} is outside {OUTCOME_PHASES}", cid, STOP_ROW)
    sha = v.get("program_sha256")
    if not programs._is_hex64(sha):
        raise CorpusStop(f"{where}: no 64-hex program_sha256", cid, STOP_ROW)
    prog, dsl = v.get("program"), None
    if prog:
        if prog.get("program_sha256", sha) != sha:
            raise CorpusStop(f"{where}: program.program_sha256 differs from program_sha256", cid, STOP_ROW)
        _check_program(prog.get("dsl"), sha, where, cid)
        dsl = prog["dsl"]
    status = v.get("record_status")
    if status not in OUTCOME_RECORD_STATUSES:
        raise CorpusStop(f"{where}: record_status {status!r} is outside {OUTCOME_RECORD_STATUSES}", cid, STOP_ROW)
    try:
        rmse_j, base_j = inner_cv_pairs(v.get("evaluation_detail"))
    except CorpusStop as err:
        raise CorpusStop(f"{where}: {err.detail}", cid, err.kind) from None
    reuse = v.get("evaluation_reuse")
    if reuse is not None:
        ident = reuse.get("compatibility_identity") or {}
        reuse = ReuseInfo(schema=reuse.get("schema"), source_context_sha256=reuse.get("source_context_sha256"),
                          input_raw_sha256=ident.get("input_raw_sha256"), evaluator_sha256=ident.get("evaluator_sha256"),
                          candidate_timeout_ms=ident.get("candidate_timeout_ms"), train_rows=ident.get("train_rows"),
                          encoded_features=ident.get("encoded_features"))
    row = OutcomeRow(line_no=line_no, phase=phase, program_sha256=sha, dsl=dsl, record_status=status,
                     transport_status=_opt_str(v, "transport_status", where, cid),
                     attempt_id=_opt_str(v, "attempt_id", where, cid),
                     node=_opt_str(v, "node", where, cid),
                     wall_us=_opt_wall(v, "wall_us", where, cid),
                     cv_mean_log_ratio=_opt_real(v, "cv_mean_log_ratio", where, cid),
                     cv_log_ratio_sd=_opt_real(v, "cv_log_ratio_sd", where, cid),
                     cv_mean_rmse_ratio=_opt_real(v, "cv_mean_rmse_ratio", where, cid),
                     cv_gate_passed=_opt_bool(v, "cv_gate_passed", where, cid),
                     rmse_j=None if rmse_j is None else tuple(rmse_j),
                     baseline_rmse_j=None if base_j is None else tuple(base_j), reuse=reuse)
    return row, full


def parse_transport(line: Any, line_no: int, ctx: Any) -> tuple[TransportRow, dict]:
    """(TransportRow, full row) of one transport line, from the TRANSPORT_TRAIN_SPEC view only. The row's context is
    _telemetry_view_context_sha256, falling back to context_sha256."""
    c = ctx_identity(ctx)
    cid, where = c.context_sha256, f"transport line {line_no}"
    full = _load_row(line, where, cid)
    v = _view(full, TRANSPORT_TRAIN_SPEC, where, cid)
    owner = v["_telemetry_view_context_sha256"] if "_telemetry_view_context_sha256" in v else v.get("context_sha256")
    if owner != cid:
        raise CorpusStop(f"{where}: transport row belongs to another context", cid, STOP_IDENTITY)
    top, prog, dsl = v.get("program_sha256"), v.get("program"), None
    if prog:
        if not programs._is_hex64(top):
            raise CorpusStop(f"{where}: a row with a program lacks a top-level program_sha256", cid, STOP_ROW)
        if prog.get("program_sha256", top) != top:
            raise CorpusStop(f"{where}: program.program_sha256 differs from program_sha256", cid, STOP_ROW)
        _check_program(prog.get("dsl"), top, where, cid)
        dsl = prog["dsl"]
    elif top is not None and not programs._is_hex64(top):
        raise CorpusStop(f"{where}: program_sha256 is not 64-hex", cid, STOP_ROW)
    row = TransportRow(line_no=line_no, attempt_id=_opt_str(v, "attempt_id", where, cid),
                       pool=_opt_str(v, "pool", where, cid), program_sha256=top, dsl=dsl)
    return row, full


def _inner_rmse(entry: Mapping | None, key: str) -> float | None:
    if entry is None:
        return None
    m = entry.get(key)
    if m is None:
        return None
    if not isinstance(m, Mapping):
        raise CorpusStop(f"inner_cv {key} is not an object", None, STOP_INNER_CV)
    x = m.get("rmse")
    if x is None:
        return None
    if not _is_real(x):
        raise CorpusStop(f"inner_cv {key}.rmse is not a number", None, STOP_INNER_CV)
    return float(x)


def inner_cv_pairs(detail: Any) -> tuple[list | None, list | None]:
    """(rmse_j, baseline_rmse_j) from evaluation_detail.inner_cv, placed by entry index.

    detail null, or inner_cv null or [] -> (None, None). Otherwise inner_cv_mode must be partitioned_kfold and
    inner_cv must hold 1 or 2 entries of kind inner_cv with distinct indices in {0, 1}; a missing fold is None.
    Any violation is CorpusStop(kind='inner_cv_shape'). The official test block is never touched."""
    if detail is None:
        return None, None
    if not isinstance(detail, Mapping):
        raise CorpusStop("evaluation_detail is not an object", None, STOP_INNER_CV)
    entries = detail.get("inner_cv")
    if entries is None or (isinstance(entries, list) and not entries):
        return None, None
    if not isinstance(entries, list):
        raise CorpusStop("inner_cv is not a list", None, STOP_INNER_CV)
    if detail.get("inner_cv_mode") != INNER_CV_MODE:
        raise CorpusStop(f"inner_cv_mode {detail.get('inner_cv_mode')!r} != {INNER_CV_MODE}", None, STOP_INNER_CV)
    if not 1 <= len(entries) <= INNER_FOLDS:
        raise CorpusStop(f"inner_cv holds {len(entries)} entries, not 1 or 2", None, STOP_INNER_CV)
    by_index: dict[int, Mapping] = {}
    for e in entries:
        if not isinstance(e, Mapping) or e.get("kind") != "inner_cv":
            raise CorpusStop("an inner_cv entry is not of kind inner_cv", None, STOP_INNER_CV)
        idx = e.get("index")
        if not _is_int(idx) or idx not in (0, 1) or idx in by_index:
            raise CorpusStop(f"inner_cv index {idx!r} is not a distinct value in {{0, 1}}", None, STOP_INNER_CV)
        by_index[idx] = e
    rmse = [_inner_rmse(by_index.get(j), "metrics") for j in (0, 1)]
    base = [_inner_rmse(by_index.get(j), "baseline_metrics") for j in (0, 1)]
    return rmse, base


