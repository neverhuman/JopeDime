def ctx_identity(ctx: Any) -> CtxIdentity:
    """CtxIdentity from a CtxIdentity, a context_sha256 string, a mapping (an epoch entry: fold or outer_fold) or
    an object with those attributes (programs.ContextRef)."""
    if isinstance(ctx, CtxIdentity):
        return ctx
    if isinstance(ctx, str):
        return CtxIdentity(ctx)
    if isinstance(ctx, Mapping):
        get = ctx.get
    else:
        def get(key, default=None):
            return getattr(ctx, key, default)
    fold = get("fold")
    if fold is None:
        fold = get("outer_fold")
    cid = get("context_sha256")
    if not programs._is_hex64(cid):
        raise ValueError("a context identity needs a 64-hex context_sha256")
    return CtxIdentity(cid, get("view_id"), get("dataset_hash"), fold)


