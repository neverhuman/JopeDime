def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="dltrain.corpus_schema", description=__doc__.split("\n", 1)[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("write-schemas", "check-schemas"):
        p = sub.add_parser(name)
        p.add_argument("--dir", default=str(SCHEMAS_DIR))
    sub.add_parser("show", help="print schema ids, sha256 and column counts")
    args = ap.parse_args(argv)
    if args.cmd == "write-schemas":
        print(json.dumps({"written": write_json_schemas(args.dir)}, sort_keys=True))
        return 0
    if args.cmd == "check-schemas":
        fails = check_json_schemas(args.dir)
        print(json.dumps({"verdict": "PASS" if not fails else "FAIL", "failures": fails}))
        return 0 if not fails else 3
    print(json.dumps({tid: {"schema_sha256": schema_sha256(s), "columns": len(s.names),
                            "json_schema_sha256": common.sha256_bytes(json_schema_bytes(tid))}
                      for tid, s in TABLES.items()}, indent=1, sort_keys=True))
    return 0


