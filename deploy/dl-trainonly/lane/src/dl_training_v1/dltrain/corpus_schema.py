def _type_fail(table_id: str, name: str, i: int, value: Any) -> CorpusStop:
    return CorpusStop(f"{table_id}.{name} row {i}: value of type {type(value).__name__} does not fit the column",
                      None, STOP_TABLE)


def _check_values(table_id: str, f: pa.Field, values: Sequence) -> None:
    """Python-level strictness where pa.array(type=...) is lenient (float -> int truncation, bool -> float, str ->
    list<string>, bytes -> string)."""
    typ = f.type
    if pa.types.is_list(typ):
        vt = typ.value_type
        for i, v in enumerate(values):
            if v is None:
                continue
            if isinstance(v, np.ndarray):
                v = v.tolist()
            if not isinstance(v, (list, tuple)):
                raise _type_fail(table_id, f.name, i, v)
            kinds = set(map(type, v))
            if pa.types.is_integer(vt):
                ok = kinds <= {int}
            elif pa.types.is_floating(vt):
                ok = kinds <= {float, int, type(None)} if vt == _F64 else True    # float32 vectors: producer-checked
            elif pa.types.is_string(vt):
                ok = kinds <= {str, type(None)}
            else:
                ok = True
            if not ok:
                raise _type_fail(table_id, f.name, i, v)
        return
    if pa.types.is_string(typ):
        want: tuple = (str,)
    elif pa.types.is_boolean(typ):
        want = (bool,)
    elif pa.types.is_integer(typ):
        for i, v in enumerate(values):
            if v is not None and not _is_int(v) and not isinstance(v, np.integer):
                raise _type_fail(table_id, f.name, i, v)
        return
    elif pa.types.is_floating(typ):
        for i, v in enumerate(values):
            if v is not None and (isinstance(v, (bool, np.bool_)) or not isinstance(v, (int, float, np.floating))):
                raise _type_fail(table_id, f.name, i, v)
        return
    else:
        return
    for i, v in enumerate(values):
        if v is not None and not isinstance(v, want):
            raise _type_fail(table_id, f.name, i, v)


_EXPOSED_VALUE_REGEX = "|".join(re.escape(s) for s in FORBIDDEN_SUBSTRINGS)
_EXPOSED_NAME_SET = pa.array(sorted(EXPOSED_NAMES), type=pa.string())


def value_pattern(table_id: str, name: str) -> str | None:
    """The allowlist pattern of one string column (or list<string> items) of a non-sealed table, else None."""
    if table_id not in VALUE_CHECKED_TABLES:
        return None
    if name.endswith("sha256"):
        return HEX64_PATTERN
    return VALUE_PATTERNS.get(name)


def _value_failures(table_id: str, f: pa.Field, arr: Any) -> list[str]:
    """Value allowlist of one column of a non-sealed table (red-team LA-5): every non-null string value fully matches
    its pattern (value_pattern), and no value outside VALUE_SCAN_EXEMPT is an exposed name or contains a forbidden
    substring. Vectorized (pyarrow.compute, RE2); returns failures, empty when the column passes."""
    if table_id not in VALUE_CHECKED_TABLES:
        return []
    is_list = pa.types.is_list(f.type)
    if not pa.types.is_string(f.type.value_type if is_list else f.type):
        return []
    if isinstance(arr, pa.ChunkedArray):
        arr = arr.combine_chunks()
    values = pc.drop_null(arr.flatten() if is_list else arr)
    if len(values) == 0:
        return []
    fails = []
    pattern = value_pattern(table_id, f.name)
    if pattern is not None:
        ok = pc.match_substring_regex(values, "^(?:" + pattern + ")$")
        bad = len(values) - int(pc.sum(pc.cast(ok, pa.int64())).as_py() or 0)
        if bad:
            fails.append(f"{f.name}: {bad} values outside the allowlist pattern")
    if pattern != HEX64_PATTERN and (table_id, f.name) not in VALUE_SCAN_EXEMPT:
        hit = pc.or_(pc.match_substring_regex(values, _EXPOSED_VALUE_REGEX), pc.is_in(values, value_set=_EXPOSED_NAME_SET))
        n = int(pc.sum(pc.cast(hit, pa.int64())).as_py() or 0)
        if n:
            fails.append(f"{f.name}: {n} values carry an exposed name")
    return fails


def json_schema_sample_failures(t: pa.Table, table: Any, every: int = 4096, limit: int = 5) -> list[str]:
    """Validate a deterministic sample of a table's rows (the first, the last and every `every`-th) against its
    generated JSON Schema 2020-12 document (verify --schema-allowlist, red-team LA-5)."""
    if t.num_rows == 0:
        return []
    tid, _ = _table_lookup(table)
    validator = jsonschema.Draft202012Validator(json_schema(tid))
    fails = []
    for i in sorted({0, t.num_rows - 1, *range(0, t.num_rows, max(1, every))}):
        err = next(iter(validator.iter_errors(t.slice(i, 1).to_pylist()[0])), None)
        if err is not None:
            fails.append(f"row {i}: JSON Schema: {err.message[:160]}")
            if len(fails) >= limit:
                break
    return fails


def _build_table(rows: Iterable[Mapping], schema: pa.Schema, table_id: str) -> pa.Table:
    names = schema.names
    want = set(names)
    cols: dict[str, list] = {n: [] for n in names}
    for i, row in enumerate(rows):
        if not isinstance(row, Mapping):
            raise CorpusStop(f"{table_id} row {i} is not a mapping", None, STOP_TABLE)
        if len(row) != len(names) or set(row) != want:
            keys = set(row)
            raise CorpusStop(f"{table_id} row {i}: keys differ from the schema (extra {sorted(keys - want)[:5]}, "
                             f"missing {sorted(want - keys)[:5]})", row.get("context_sha256"), STOP_TABLE)
        for n in names:
            cols[n].append(row[n])
    arrays = []
    for f in schema:
        values = cols[f.name]
        _check_values(table_id, f, values)
        try:
            arr = pa.array(values, type=f.type)
        except (pa.ArrowInvalid, pa.ArrowTypeError, OverflowError, TypeError, ValueError) as err:
            raise CorpusStop(f"{table_id}.{f.name}: {err}", None, STOP_TABLE) from None
        if not f.nullable and arr.null_count:
            raise CorpusStop(f"{table_id}.{f.name}: {arr.null_count} nulls in a non-nullable column", None, STOP_TABLE)
        if pa.types.is_list(f.type):
            if f.name in _ITEMS_NOT_NULL and arr.flatten().null_count:
                raise CorpusStop(f"{table_id}.{f.name}: null list items", None, STOP_TABLE)
            if f.name in _PAIR_LISTS:
                lengths = pc.list_value_length(arr).to_pylist()
                if any(n is not None and n != 2 for n in lengths):
                    raise CorpusStop(f"{table_id}.{f.name}: a present list does not hold 2 values", None, STOP_TABLE)
        if f.name in _ENUMS:
            bad = {v for v in values if v is not None} - set(_ENUMS[f.name])
            if bad:
                raise CorpusStop(f"{table_id}.{f.name}: values outside {_ENUMS[f.name]}: {sorted(bad)[:3]}", None,
                                 STOP_TABLE)
        fails = _value_failures(table_id, f, arr)
        if fails:
            raise CorpusStop(f"{table_id}.{fails[0]}", None, STOP_TABLE)
        arrays.append(arr)
    if table_id == TRAIN_RECORD_ID:
        known = frozenset(OUTCOME_CLASSES)
        for i, (toks, n, outcome) in enumerate(zip(cols["tokens"], cols["length"], cols["outcome"])):
            if len(toks) != n or n < 2 or toks[0] != dsl_tokenizer.BOS or toks[-1] != dsl_tokenizer.EOS:
                raise CorpusStop(f"{table_id} row {i}: tokens are not BOS..EOS of `length` ids", None, STOP_TABLE)
            if outcome not in known and not OUTCOME_RE.match(outcome):
                raise CorpusStop(f"{table_id} row {i}: outcome {outcome!r} is outside the outcome classes", None,
                                 STOP_TABLE)
    return pa.Table.from_arrays(arrays, schema=schema)


def records_table(rows: Iterable[Mapping]) -> pa.Table:
    return _build_table(rows, TRAIN_RECORD_SCHEMA, TRAIN_RECORD_ID)


def contexts_table(rows: Iterable[Mapping]) -> pa.Table:
    return _build_table(rows, TRAIN_CONTEXT_SCHEMA, TRAIN_CONTEXT_ID)


def exposed_table(rows: Iterable[Mapping]) -> pa.Table:
    return _build_table(rows, EXPOSED_RECORD_SCHEMA, EXPOSED_RECORD_ID)


def lineage_table(rows: Iterable[Mapping]) -> pa.Table:
    return _build_table(rows, LINEAGE_RECORD_SCHEMA, LINEAGE_RECORD_ID)


def refused_table(rows: Iterable[Mapping]) -> pa.Table:
    return _build_table(rows, REFUSED_RECORD_SCHEMA, REFUSED_RECORD_ID)


def parquet_bytes(table: pa.Table, *, sealed: bool = False) -> bytes:
    """The shard serialization (spec §3.5): zstd level 6, dictionary pages, statistics unless sealed, the Arrow
    schema stored, row groups of at most 65,536 rows, and list children named "item" (use_compliant_nested_type=False,
    so a read-back schema equals the declared one exactly). Deterministic bytes for equal tables."""
    sink = pa.BufferOutputStream()
    with pq.ParquetWriter(sink, table.schema, compression="zstd", compression_level=ZSTD_LEVEL, use_dictionary=True,
                          write_statistics=not sealed, store_schema=True, use_compliant_nested_type=False) as w:
        w.write_table(table, row_group_size=ROW_GROUP_ROWS)
    return sink.getvalue().to_pybytes()


def _paths(paths: Any) -> list:
    if isinstance(paths, (str, Path)):
        return [paths]
    return list(paths)


def _read_rows(paths: Any, schema: pa.Schema, table_id: str) -> list[dict]:
    rows: list[dict] = []
    for p in _paths(paths):
        pf = pq.ParquetFile(p)
        if not pf.schema_arrow.equals(schema, check_metadata=False):
            raise CorpusStop(f"{p}: schema is not {table_id}", None, STOP_SCHEMA)
        rows.extend(pf.read(use_threads=False).to_pylist())
    return rows


def read_records(paths: Any) -> list[dict]:
    """TRAIN_RECORD_SCHEMA rows as dicts (single-threaded), as sampler.Corpus.build and labels.label_corpus take them."""
    return _read_rows(paths, TRAIN_RECORD_SCHEMA, TRAIN_RECORD_ID)


def read_contexts(paths: Any) -> list[dict]:
    """TRAIN_CONTEXT_SCHEMA rows as dicts (single-threaded); y_train is a list of floats."""
    return _read_rows(paths, TRAIN_CONTEXT_SCHEMA, TRAIN_CONTEXT_ID)


def is_sealed_path(path: Path | str) -> bool:
    parts = Path(path).parts
    return "heldout" in parts or "exposed" in parts


def _decode_failures(t: pa.Table, schema: pa.Schema, table_id: str, max_seq: int | None = None) -> list[str]:
    fails = []
    if max_seq is not None and table_id == TRAIN_RECORD_ID and t.num_rows:
        longest = max(t.column("length").to_pylist())
        if longest > max_seq:
            fails.append(f"length {longest} > max_seq {max_seq}")
    for f in schema:
        col = t.column(f.name)
        if not f.nullable and col.null_count:
            fails.append(f"{f.name}: {col.null_count} nulls")
        if pa.types.is_list(f.type):
            arr = col.combine_chunks()
            if f.name in _ITEMS_NOT_NULL and arr.flatten().null_count:
                fails.append(f"{f.name}: null list items")
            if f.name in _PAIR_LISTS:
                lengths = pc.list_value_length(arr).to_pylist()
                if any(n is not None and n != 2 for n in lengths):
                    fails.append(f"{f.name}: a present list does not hold 2 values")
        if f.name in _ENUMS:
            bad = {v for v in col.to_pylist() if v is not None} - set(_ENUMS[f.name])
            if bad:
                fails.append(f"{f.name}: values outside the enum: {sorted(bad)[:3]}")
        fails.extend(_value_failures(table_id, f, col))
    if table_id == TRAIN_RECORD_ID and t.num_rows:
        toks, lengths = t.column("tokens").to_pylist(), t.column("length").to_pylist()
        for i, (tk, n) in enumerate(zip(toks, lengths)):
            if tk is None or len(tk) != n or n < 2 or tk[0] != dsl_tokenizer.BOS or tk[-1] != dsl_tokenizer.EOS:
                fails.append(f"row {i}: tokens are not BOS..EOS of `length` ids")
                break
        bad = [o for o in t.column("outcome").to_pylist() if o is None or not OUTCOME_RE.match(o)]
        if bad:
            fails.append(f"outcome outside the classes: {sorted(set(map(str, bad)))[:3]}")
    if table_id == TRAIN_CONTEXT_ID and t.num_rows:
        for i, (y, n) in enumerate(zip(t.column("y_train").to_pylist(), t.column("n_train").to_pylist())):
            if y is None or len(y) != n:
                fails.append(f"row {i}: len(y_train) != n_train")
                break
    if table_id == REFUSED_RECORD_ID and t.num_rows:
        if "train_fit" in set(t.column("split_role").to_pylist()):
            fails.append("a train_fit program is refused (train_fit over max_seq is a STOP)")
    return fails


def check_parquet(path: Path | str, schema: pa.Schema, decode: bool = False, *, sealed: bool | None = None,
                  max_row_group: int = ROW_GROUP_ROWS, max_seq: int | None = None,
                  json_sample: int | None = None) -> list[str]:
    """Failures of one Parquet file (empty means it passes): the Arrow schema equals `schema` exactly (pa.Schema.equals
    and the same schema string, so list child names count too), the key-value metadata is exactly {ARROW:schema},
    every column chunk is ZSTD, row groups hold <= 65,536 rows, and files without statistics (`sealed`: heldout/**,
    exposed/**, inferred from the path unless given; corpus_build also passes it for the lineage table) carry no
    column statistics. With decode: non-null columns hold no null, list items that must be present are, rmse lists
    hold 2 values, enumerated columns stay in their domains (tokens BOS..EOS of `length` ids; outcome classes;
    length <= max_seq when max_seq is given), non-sealed string columns pass the value allowlist, and with
    json_sample a deterministic sample of rows (every json_sample-th) validates against the table's JSON Schema."""
    path = Path(path)
    sealed = is_sealed_path(path) if sealed is None else sealed
    table_id = next((tid for tid, s in TABLES.items() if s is schema or s.equals(schema)), None)
    fails: list[str] = []
    pf = pq.ParquetFile(path)
    schema_ok = pf.schema_arrow.equals(schema, check_metadata=False)
    if not schema_ok:
        fails.append("Arrow schema differs from the expected table schema")
    elif pf.schema_arrow.to_string(show_schema_metadata=False) != schema.to_string(show_schema_metadata=False):
        fails.append("Arrow schema string differs (list child names; write with use_compliant_nested_type=False, "
                     "as corpus_schema.parquet_bytes does)")
    md = pf.metadata
    if set((md.metadata or {}).keys()) != {b"ARROW:schema"}:
        fails.append(f"key-value metadata is {sorted((md.metadata or {}).keys())}, not only ARROW:schema")
    for g in range(md.num_row_groups):
        rg = md.row_group(g)
        if rg.num_rows > max_row_group:
            fails.append(f"row group {g} holds {rg.num_rows} rows > {max_row_group}")
        for j in range(rg.num_columns):
            cc = rg.column(j)
            if cc.compression != "ZSTD":
                fails.append(f"row group {g} column {cc.path_in_schema} is {cc.compression}, not ZSTD")
            if sealed and cc.is_stats_set:
                fails.append(f"row group {g} column {cc.path_in_schema} carries statistics in a sealed file")
    if decode and schema_ok:
        t = pf.read(use_threads=False)
        fails.extend(_decode_failures(t, schema, table_id or "?", max_seq))
        if json_sample is not None and table_id is not None:
            fails.extend(json_schema_sample_failures(t, table_id, json_sample))
    return fails


