#!/usr/bin/env python3
"""Validate the committed remediation records and render PROGRESS.md from them (W12-T03).

The view composes the findings register, finding dispositions, task status and claims. Each input
is first accepted by its own verifier, and the view is regenerated from those validated records
only:

- A finding counts as closed only through a verified closing disposition. Task states, claims and
  this view never close one.
- Counts come from record fields, never from titles, notes or key order, so presentation metadata
  cannot change them.
- The exact input digests are part of the view, so a view is bound to the records it came from.
- Custody verification depends on the host (a CI runner cannot read custody), so the view shows
  where evidence lives, never whether this host happened to verify it.
"""
import argparse
import hashlib
import json
from pathlib import Path

import task_status
import verify_claims
import verify_dispositions

CORE = Path(__file__).resolve().parents[1]
INPUTS = ("findings/register.json", "findings/dispositions.json",
          "work-orders/task-status.json", "claims/claims.json")
STATES = task_status.STATES


def require(condition, message):
    if not condition:
        raise ValueError(message)


def package(order):
    """`W01` (task file prefix) and `W1` (register work package) name the same work order."""
    return f"W{int(order[1:])}"


def collect(core=CORE):
    dispositions = verify_dispositions.verify(core / "findings")
    headings, tasks = task_status.verify(core / "work-orders")
    claims_path = core / "claims" / "claims.json"
    verify_claims.verify(claims_path, root=core.parents[2])
    register = json.loads((core / "findings" / "register.json").read_text())
    claims = json.loads(claims_path.read_text())
    digests = {name: hashlib.sha256((core / name).read_bytes()).hexdigest() for name in INPUTS}
    return {"digests": digests, "entries": register["entries"],
            "closed": set(dispositions["closed_findings"]),
            "dispositions": dispositions["dispositions"],
            "headings": headings, "tasks": tasks, "claims": claims}


def render(data):
    entries, closed, headings, tasks = data["entries"], data["closed"], data["headings"], data["tasks"]
    packages = sorted({e["work_package"] for e in entries} | {package(h["order"]) for h in headings.values()},
                      key=lambda p: int(p[1:]))
    lines = ["# Regression remediation progress view", "",
             "Generated by `docs/internal/core-ip/tools/progress_view.py` from the validated records below; do not edit.",
             "A finding closes only through a verified closing disposition in `findings/dispositions.json`;",
             "task states, claims and this view never close one. Fixture proof is not CI verification, and",
             "neither is live qualification.", "",
             "## Inputs", "", "| Record | SHA-256 |", "|---|---|"]
    lines += [f"| `{name}` | `{digest}` |" for name, digest in data["digests"].items()] + [""]

    header = ["Work order", "Gaps", "Improvements", "Open", "Closed", "Tasks", *STATES]
    lines += ["## Findings and tasks by primary work order", "",
              "Task columns count tasks holding each state; a task can hold several.", "",
              "| " + " | ".join(header) + " |", "|---|" + "---:|" * (len(header) - 1)]
    totals = [0] * (len(header) - 1)
    for name in packages:
        owned = [e for e in entries if e["work_package"] == name]
        owned_tasks = [t for t, h in headings.items() if package(h["order"]) == name]
        row = [sum(e["kind"] == "gap" for e in owned), sum(e["kind"] == "improvement" for e in owned),
               sum(e["id"] not in closed for e in owned), sum(e["id"] in closed for e in owned),
               len(owned_tasks)]
        row += [sum(state in tasks[t]["states"] for t in owned_tasks) for state in STATES]
        totals = [a + b for a, b in zip(totals, row)]
        lines.append(f"| {name} | " + " | ".join(map(str, row)) + " |")
    lines += ["| **Total** | " + " | ".join(f"**{v}**" for v in totals) + " |", ""]

    blocked = sorted((t for t in tasks if "blocked" in tasks[t]["states"]),
                     key=lambda t: (int(t[1:].split("-")[0]), int(t.split("-T")[1])))
    lines += ["## Pending gates", "", "| Task | Blocker |", "|---|---|"]
    lines += [f"| {t} {headings[t]['title']} | {tasks[t]['blocker']} |" for t in blocked] or ["| — | — |"]
    lines.append("")

    evidence = data["claims"]["evidence"]
    lines += ["## Claims", "",
              "Evidence location is shown, not this host's verification result: custody evidence is",
              "verified by `verify_claims.py --require-custody` where custody is readable.", "",
              "| Claim | Stage | Status | Evidence (kind, location) |", "|---|---|---|---|"]
    for claim in sorted(data["claims"]["claims"], key=lambda c: c["id"]):
        cited = "; ".join(f"{n} ({evidence[n]['kind']}, {evidence[n]['location']})" for n in claim["evidence"])
        lines.append(f"| {claim['id']} | {claim['stage']} | {claim['status']} | {cited} |")
    lines.append("")

    planned = sum(tasks[t]["states"] == ["planned"] for t in tasks)
    undisposed = len(entries) - sum(data["dispositions"].values())
    lines += ["## Not progress", "",
              f"- Tasks still only planned (no commits or evidence): {planned} of {len(tasks)}.",
              f"- Findings without any disposition record: {undisposed} of {len(entries)}.",
              f"- Findings closed: {len(closed)} of {len(entries)}.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--core", type=Path, default=CORE)
    parser.add_argument("--write", action="store_true", help="rewrite work-orders/PROGRESS.md")
    args = parser.parse_args()
    data = collect(args.core)
    text = render(data)
    target = args.core / "work-orders" / "PROGRESS.md"
    if args.write:
        target.write_text(text)
    else:
        require(target.read_text() == text, "PROGRESS.md is stale; regenerate with --write")
    print(json.dumps({"findings": len(data["entries"]), "closed": len(data["closed"]),
                      "tasks": len(data["tasks"])}, sort_keys=True))
