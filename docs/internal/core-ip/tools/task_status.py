#!/usr/bin/env python3
"""Validate the W1-W12 task-status record and render STATUS.md deterministically (W12-T03).

Every numbered task heading in the work orders has exactly one record. States use the execution
contract's vocabulary and are scoped observations, not a ladder: `planned` stands alone; any other
state needs commits or evidence; `fixture-proven` names its proving tests; `CI-verified` binds a run,
attempt and head; `live-qualified` and `measurement-complete` bind live evidence; `blocked` states
its blocker. The rendered view is regenerated from these records only, so presentation cannot
strengthen a task's evidence.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1] / "work-orders"
STATES = ("planned", "reproduced", "implemented", "fixture-proven", "CI-verified",
          "live-qualified", "measurement-complete", "blocked")
SHA = re.compile(r"[0-9a-f]{40}")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def task_headings(root):
    tasks = {}
    for path in sorted(root.glob("W*.tasks.md")):
        for match in re.finditer(r"^### (W\d+-T\d+) — (.+)$", path.read_text(), re.M):
            require(match[1] not in tasks, f"duplicate task heading {match[1]}")
            tasks[match[1]] = {"title": match[2].strip(), "order": path.name.split("-", 1)[0]}
    return tasks


def verify(root=ROOT):
    headings = task_headings(root)
    record = json.loads((root / "task-status.json").read_text())
    require(record.get("schema") == "jope.regression-task-status/v1", "task status schema")
    tasks = record.get("tasks", {})
    require(set(tasks) == set(headings),
            f"task records differ from headings: missing {sorted(set(headings) - set(tasks))[:4]}, "
            f"extra {sorted(set(tasks) - set(headings))[:4]}")
    for task, item in tasks.items():
        states = item.get("states")
        require(isinstance(states, list) and states and len(set(states)) == len(states)
                and set(states) <= set(STATES), f"{task}: states")
        require("planned" not in states or states == ["planned"], f"{task}: planned stands alone")
        commits = item.get("commits", [])
        require(all(SHA.fullmatch(c) for c in commits), f"{task}: commits must be full SHAs")
        if states != ["planned"] and states != ["blocked"]:
            require(commits or item.get("evidence"), f"{task}: progress needs commits or evidence")
        if "fixture-proven" in states:
            require(item.get("tests"), f"{task}: fixture-proven needs proving tests")
        if "CI-verified" in states:
            ci = item.get("ci", {})
            require(isinstance(ci.get("run_id"), int) and isinstance(ci.get("attempt"), int)
                    and SHA.fullmatch(ci.get("head_sha") or ""), f"{task}: CI-verified needs run binding")
        if {"live-qualified", "measurement-complete"} & set(states):
            require(item.get("live_evidence"), f"{task}: live/measurement states need live evidence")
        if "blocked" in states:
            require(item.get("blocker"), f"{task}: blocked needs its blocker")
        require(isinstance(item.get("remaining", ""), str), f"{task}: remaining")
    return headings, tasks


def render(headings, tasks):
    lines = ["# Regression remediation task status", "",
             "Generated by `docs/internal/core-ip/tools/task_status.py` from `task-status.json`; do not edit.",
             "States are scoped observations (execution contract), not an automatic ladder. Fixture proof is",
             "not CI verification, and neither is live qualification. No finding closes through this view.", ""]
    counts = {state: sum(state in t["states"] for t in tasks.values()) for state in STATES}
    lines += ["| State | Tasks |", "|---|---:|"] + [f"| {s} | {counts[s]} |" for s in STATES] + [""]
    for order in sorted({h["order"] for h in headings.values()}, key=lambda o: int(o[1:])):
        lines += [f"## {order}", "", "| Task | States | Evidence | Remaining or blocker |", "|---|---|---|---|"]
        for task in sorted((t for t, h in headings.items() if h["order"] == order),
                           key=lambda t: int(t.split("-T")[1])):
            item = tasks[task]
            evidence = [c[:12] for c in item.get("commits", [])] + item.get("tests", [])[:3]
            if len(item.get("tests", [])) > 3:
                evidence.append(f"+{len(item['tests']) - 3} tests")
            note = item.get("blocker") or item.get("remaining", "")
            lines.append(f"| {task} {headings[task]['title']} | {', '.join(item['states'])} | "
                         f"{'; '.join(evidence) or '—'} | {note or '—'} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--write", action="store_true", help="rewrite STATUS.md")
    args = parser.parse_args()
    headings, tasks = verify(args.root)
    text = render(headings, tasks)
    target = args.root / "STATUS.md"
    if args.write:
        target.write_text(text)
    else:
        require(target.read_text() == text, "STATUS.md is stale; regenerate with --write")
    print(json.dumps({"tasks": len(tasks), "states": {s: sum(s in t["states"] for t in tasks.values())
                                                       for s in STATES}}, sort_keys=True))
