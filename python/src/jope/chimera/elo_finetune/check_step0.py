"""Step-0 harness validation: with UNMODIFIED weights, compare the tier-2
protocol against the frozen tabpfn_v3_regressor report rmse.

Finding (2026-07-02): the frozen reports were generated by the actual
`tabpfn` library on super1, which predict_reg's 6-view protocol tracks
closely but not bit-wise (observed: median |Δrmse| ≈ 9e-4, p90 ≈ 1e-2).
The authoritative protocol for this project is therefore OUR deterministic
tier-2; step-0 rebases base_elo on it (base and trained weights are always
compared under the identical protocol, so the report discrepancy cancels).
This check now guards against drift/bugs in OUR protocol: it must stay in
the same closeness envelope vs the reports (median < 2e-3 by default).

Usage: python3 -m python.elo_finetune.check_step0 --device cuda:0 \
           [--split val] [--sample 24] [--tolerance 2e-3]
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np
import torch

from .eval_protocol import ProtocolRunner
from .model_io import load_regressor
from .pack import DEFAULT_PACK_DIR, OUR_ALGORITHM, FablePack


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pack-dir", type=Path, default=DEFAULT_PACK_DIR)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--split", default="val")
    parser.add_argument("--sample", type=int, default=24, help="0 = full split")
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--tolerance", type=float, default=2e-3)
    args = parser.parse_args()

    pack = FablePack(args.pack_dir / "fable_real_v1.pack", preload=True)
    device = torch.device(args.device)
    model = load_regressor(device=device)
    runner = ProtocolRunner(model, device)
    ours = pack.algo_id[OUR_ALGORITHM]

    indices = pack.split_indices(args.split)
    if args.sample:
        rng = np.random.default_rng(args.seed)
        indices = rng.choice(indices, size=min(args.sample, len(indices)), replace=False)

    diffs, rows = [], []
    started = time.time()
    for i in indices.tolist():
        view = pack.dataset(i)
        pos = np.nonzero(view.util_algo_ids == ours)[0]
        if pos.size == 0:
            continue
        frozen_rmse = -float(view.util_values[pos[0]])
        got_rmse = runner.tier2_rmse(view)
        diffs.append(abs(got_rmse - frozen_rmse))
        rows.append((view.dataset_id, frozen_rmse, got_rmse))

    diffs_arr = np.array(diffs)
    median = float(np.median(diffs_arr))
    result = {
        "split": args.split,
        "datasets": len(diffs),
        "median_abs_diff": median,
        "p90_abs_diff": float(np.quantile(diffs_arr, 0.9)),
        "max_abs_diff": float(diffs_arr.max()),
        "tolerance": args.tolerance,
        "pass": median < args.tolerance,
        "seconds": round(time.time() - started, 1),
    }
    print(json.dumps(result, indent=2))
    worst = sorted(zip(diffs, rows), reverse=True)[:5]
    for diff, (dataset_id, frozen, got) in worst:
        print(f"  worst: {dataset_id} frozen={frozen:.6g} tier2={got:.6g} |Δ|={diff:.3g}")
    if not result["pass"]:
        raise SystemExit("step-0 harness validation FAILED")


if __name__ == "__main__":
    main()
