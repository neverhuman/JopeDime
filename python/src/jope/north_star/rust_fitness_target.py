#!/usr/bin/env python3
"""
NORTH STAR Phase D (NS5): Rust-Only Fitness Target for Flywheel Self-Play
=========================================================================
Per NORTH_STAR.md Phase D ("Flywheel outputs ONLY Rust target for fitness tests"):
  1. Strips out all 9 non-Rust targets (`c`, `cpp`, `csharp`, `fortran`, `go`, `haskell`,
     `java`, `python`, `typescript`) during flywheel verification, cutting codegen and
     compilation work by 10x.
  2. Emits a standalone zero-dependency Rust library (`predict_row` for Regression and
     Platt-calibrated `predict_proba_row` for Binary Classification) with `#[no_mangle]
     pub extern "C" fn predict_batch_f64(...)` for zero-subprocess `ctypes` fitness
     verification on `xbabe3` / `xbabe4`.
"""

from __future__ import annotations

import ctypes
import hashlib
import json
import math
import subprocess
import tempfile
import time
from pathlib import Path

import numpy as np

ALLOWED_FLYWHEEL_TARGETS = ("rust",)


def _require_1d_finite_array(name: str, arr: np.ndarray) -> np.ndarray:
    out = np.asarray(arr, dtype=np.float64)
    if out.ndim != 1 or out.size == 0:
        raise ValueError(f"{name} must be a non-empty 1D array, got shape {out.shape}")
    if not np.isfinite(out).all():
        raise ValueError(f"{name} must contain only finite values")
    return out


def _require_finite_scalar(name: str, val: float) -> float:
    fval = float(val)
    if not math.isfinite(fval):
        raise ValueError(f"{name} must be a finite scalar, got {val!r}")
    return fval


def emit_rust_only_flywheel_source(
    dataset_id: str,
    selected_dsl: str,
    weights: np.ndarray,
    intercept: float,
    mu_tr: np.ndarray,
    sd_tr: np.ndarray,
    is_binary: bool = False,
    platt_a: float = 1.0,
    platt_b: float = 0.0,
    pred_mu: float = 0.0,
    pred_sd: float = 1.0,
) -> str:
    """
    Emits a standalone Rust source file (`lib.rs`) for flywheel fitness evaluation,
    supporting both continuous regression (`predict_row`) and binary classification
    (`predict_proba_row`), plus a C ABI batch entry point (`predict_batch_f64`) so
    the flywheel harness can evaluate holdout fitness via `ctypes` with zero CLI parsing.
    """
    if not isinstance(dataset_id, str) or not dataset_id.strip():
        raise ValueError("dataset_id must be a non-empty string")
    if any(ch in dataset_id for ch in ("\n", "\r", "\x00")):
        raise ValueError("dataset_id must not contain newline or NUL characters")
    if not isinstance(selected_dsl, str) or not selected_dsl.strip():
        raise ValueError("selected_dsl must be a non-empty string")
    if "\x00" in selected_dsl:
        raise ValueError("selected_dsl must not contain NUL characters")

    mu_arr = _require_1d_finite_array("mu_tr", mu_tr)
    sd_arr = _require_1d_finite_array("sd_tr", sd_tr)
    w_arr = _require_1d_finite_array("weights", weights)
    if mu_arr.shape != sd_arr.shape:
        raise ValueError(f"mu_tr and sd_tr must have identical shape, got {mu_arr.shape} vs {sd_arr.shape}")
    if w_arr.shape[0] > mu_arr.shape[0]:
        raise ValueError(
            f"weights length ({w_arr.shape[0]}) cannot exceed feature count ({mu_arr.shape[0]})"
        )

    intercept_f = _require_finite_scalar("intercept", intercept)
    platt_a_f = _require_finite_scalar("platt_a", platt_a)
    platt_b_f = _require_finite_scalar("platt_b", platt_b)
    pred_mu_f = _require_finite_scalar("pred_mu", pred_mu)
    pred_sd_f = _require_finite_scalar("pred_sd", pred_sd)
    if abs(pred_sd_f) <= 0.0:
        raise ValueError("pred_sd must be non-zero")

    p = int(mu_arr.shape[0])
    d = int(w_arr.shape[0])

    def _fmt_arr(arr: np.ndarray) -> str:
        return ", ".join(f"{float(x):.9e}_f64" for x in arr.reshape(-1))

    dsl_escaped = (
        selected_dsl.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
    )
    return f"""// Auto-generated by JopeDime NORTH_STAR Phase D Flywheel (Rust-Only Fitness Target)
// dataset_id: {dataset_id}
// task_type: {"binary_classification" if is_binary else "regression"}
pub const SELECTED_DSL: &str = "{dsl_escaped}";
pub const N_RAW_FEATURES: usize = {p};
pub const N_WEIGHTS: usize = {d};
pub const IS_BINARY: bool = {"true" if is_binary else "false"};
pub const INTERCEPT: f64 = {intercept_f:.9e}_f64;
pub const PLATT_A: f64 = {platt_a_f:.9e}_f64;
pub const PLATT_B: f64 = {platt_b_f:.9e}_f64;
pub const PRED_MU: f64 = {pred_mu_f:.9e}_f64;
pub const PRED_SD: f64 = {float(max(abs(pred_sd_f), 1e-6)):.9e}_f64;

pub static MU_TR: [f64; {p}] = [{_fmt_arr(mu_arr)}];
pub static SD_TR: [f64; {p}] = [{_fmt_arr(sd_arr)}];
pub static WEIGHTS: [f64; {d}] = [{_fmt_arr(w_arr)}];

#[inline]
pub fn predict_raw_row(x: &[f64]) -> f64 {{
    let mut acc: f64 = INTERCEPT;
    let lim = if x.len() < N_RAW_FEATURES {{ x.len() }} else {{ N_RAW_FEATURES }};
    let mut j: usize = 0;
    while j < lim && j < N_WEIGHTS {{
        let v = x[j];
        let z = if v.is_finite() {{
            let s = SD_TR[j];
            let inv = if s.abs() > 1e-12 {{ 1.0 / s }} else {{ 1.0 }};
            ((v - MU_TR[j]) * inv).clamp(-8.0, 8.0)
        }} else {{
            0.0
        }};
        acc += z * WEIGHTS[j];
        j += 1;
    }}
    acc
}}

#[inline]
pub fn predict_proba_row(x: &[f64]) -> f64 {{
    let raw = predict_raw_row(x);
    let z = (raw - PRED_MU) / PRED_SD;
    let logit = (PLATT_A * z + PLATT_B).clamp(-15.0, 15.0);
    1.0 / (1.0 + (-logit).exp())
}}

#[inline]
pub fn predict_row(x: &[f64]) -> f64 {{
    if IS_BINARY {{
        predict_proba_row(x)
    }} else {{
        predict_raw_row(x)
    }}
}}

#[no_mangle]
pub unsafe extern "C" fn predict_batch_f64(
    x_ptr: *const f64,
    n_rows: usize,
    n_cols: usize,
    out_ptr: *mut f64,
) {{
    if x_ptr.is_null() || out_ptr.is_null() {{
        return;
    }}
    let mut i: usize = 0;
    while i < n_rows {{
        let row = core::slice::from_raw_parts(x_ptr.add(i * n_cols), n_cols);
        *out_ptr.add(i) = predict_row(row);
        i += 1;
    }}
}}
"""


def compile_and_eval_rust_fitness(
    rust_src: str,
    X_val: np.ndarray,
    y_val: np.ndarray,
    is_binary: bool = False,
) -> dict[str, object]:
    """
    Compiles `rust_src` with `rustc --crate-type cdylib -O` into a temporary shared library,
    evaluates `predict_batch_f64` on `X_val`, and computes exact fitness (`hold_r2` for
    regression; `brier_r2` and `roc_auc` for binary classification).
    """
    X_arr = np.asarray(X_val, dtype=np.float64)
    if X_arr.ndim != 2 or X_arr.shape[0] < 2 or X_arr.shape[1] < 1:
        raise ValueError(
            f"X_val must be a 2D array with at least 2 rows and 1 column, got shape {X_arr.shape}"
        )
    y_c = np.asarray(y_val, dtype=np.float64)
    if y_c.ndim != 1 or y_c.shape[0] != X_arr.shape[0]:
        raise ValueError(
            f"y_val must be a 1D array matching X_val rows ({X_arr.shape[0]}), got shape {y_c.shape}"
        )
    if not np.isfinite(y_c).all():
        raise ValueError("y_val must contain only finite holdout labels")

    if not is_binary:
        sst_raw = float(np.sum((y_c - np.mean(y_c)) ** 2))
        if sst_raw <= 1e-12:
            raise ValueError("Degenerate constant regression holdout target: SST <= 1e-12")
    else:
        y_min, y_max = float(np.min(y_c)), float(np.max(y_c))
        if (y_max - y_min) <= 1e-5:
            raise ValueError("Degenerate single-class binary holdout target")
        near_endpoints = (np.abs(y_c - y_min) <= 1e-5) | (np.abs(y_c - y_max) <= 1e-5)
        if not bool(np.all(near_endpoints)):
            raise ValueError("Binary holdout target must contain exactly two distinct classes")

    t0 = time.perf_counter()
    with tempfile.TemporaryDirectory(prefix="jope_ns5_rust_") as tmpdir:
        tmp = Path(tmpdir)
        rs_path = tmp / "lib.rs"
        so_path = tmp / "libfitness.so"
        rs_path.write_text(rust_src, encoding="utf-8")

        t_comp0 = time.perf_counter()
        subprocess.run(
            [
                "rustc",
                "--edition=2021",
                "--crate-type=cdylib",
                "-C",
                "opt-level=2",
                str(rs_path),
                "-o",
                str(so_path),
            ],
            check=True,
            capture_output=True,
            text=True,
        )
        compile_ms = (time.perf_counter() - t_comp0) * 1000.0

        lib = ctypes.CDLL(str(so_path))
        fn = lib.predict_batch_f64
        fn.argtypes = [
            ctypes.POINTER(ctypes.c_double),
            ctypes.c_size_t,
            ctypes.c_size_t,
            ctypes.POINTER(ctypes.c_double),
        ]
        fn.restype = None

        X_c = np.ascontiguousarray(X_arr, dtype=np.float64)
        n_rows, n_cols = X_c.shape
        preds = np.zeros(n_rows, dtype=np.float64)

        t_exec0 = time.perf_counter()
        fn(
            X_c.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
            n_rows,
            n_cols,
            preds.ctypes.data_as(ctypes.POINTER(ctypes.c_double)),
        )
        exec_ms = (time.perf_counter() - t_exec0) * 1000.0

    if not np.isfinite(preds).all():
        raise ValueError("Rust fitness evaluation produced non-finite predictions")

    if not is_binary:
        sse = float(np.sum((y_c - preds) ** 2))
        sst = float(max(sst_raw, 1e-12))
        r2 = 1.0 - sse / sst
        return {
            "task_type": "regression",
            "fitness_r2": r2,
            "compile_ms": compile_ms,
            "exec_ms": exec_ms,
            "total_ms": (time.perf_counter() - t0) * 1000.0,
            "rust_sha256": hashlib.sha256(rust_src.encode("utf-8")).hexdigest(),
        }
    else:
        y_bin = (y_c - y_min) / max(y_max - y_min, 1e-6)
        p1 = float(np.clip(np.mean(y_bin), 1e-4, 1.0 - 1e-4))
        brier = float(np.mean((y_bin - preds) ** 2))
        brier_r2 = 1.0 - brier / (p1 * (1.0 - p1))
        order = np.argsort(preds, kind="mergesort")
        p_s = preds[order]
        y_s = y_bin[order]
        first_pos = np.searchsorted(p_s, p_s, side="left")
        last_pos = np.searchsorted(p_s, p_s, side="right") - 1
        ranks = 0.5 * (first_pos.astype(np.float64) + last_pos.astype(np.float64)) + 1.0
        n_pos = float(np.sum(y_s > 0.5))
        n_neg = float(np.sum(y_s <= 0.5))
        auc = float((np.sum(ranks[y_s > 0.5]) - 0.5 * n_pos * (n_pos + 1.0)) / max(n_pos * n_neg, 1.0))
        return {
            "task_type": "binary_classification",
            "fitness_r2": brier_r2,
            "brier_r2": brier_r2,
            "roc_auc": auc,
            "compile_ms": compile_ms,
            "exec_ms": exec_ms,
            "total_ms": (time.perf_counter() - t0) * 1000.0,
            "rust_sha256": hashlib.sha256(rust_src.encode("utf-8")).hexdigest(),
        }


def run_self_test() -> dict:
    rng = np.random.default_rng(123)
    X = rng.normal(size=(200, 8))
    w_true = np.array([1.5, -0.8, 0.5, 0.0, 0.0, 0.3, -0.4, 0.2])
    y_reg = X @ w_true + 0.2 * rng.normal(size=200)
    mu = np.zeros(8)
    sd = np.ones(8)

    src_reg = emit_rust_only_flywheel_source(
        dataset_id="ns5_reg_smoke",
        selected_dsl="(pipe X (standardize) (ridge_gcv))",
        weights=w_true,
        intercept=0.0,
        mu_tr=mu,
        sd_tr=sd,
        is_binary=False,
    )
    res_reg = compile_and_eval_rust_fitness(src_reg, X, y_reg, is_binary=False)
    assert res_reg["fitness_r2"] > 0.95

    logits = X @ w_true
    probs = 1.0 / (1.0 + np.exp(-logits))
    y_bin = (rng.uniform(size=200) < probs).astype(np.float64)
    src_bin = emit_rust_only_flywheel_source(
        dataset_id="ns5_bin_smoke",
        selected_dsl="(pipe X (standardize) (ridge_gcv))",
        weights=w_true,
        intercept=0.0,
        mu_tr=mu,
        sd_tr=sd,
        is_binary=True,
        platt_a=float(np.std(logits)),
        platt_b=0.0,
        pred_mu=float(np.mean(logits)),
        pred_sd=float(np.std(logits)),
    )
    res_bin = compile_and_eval_rust_fitness(src_bin, X, y_bin, is_binary=True)
    assert res_bin["roc_auc"] > 0.80

    report = {
        "task": "NS5_RUST_ONLY_FITNESS_TARGET",
        "status": "PASS",
        "allowed_targets": list(ALLOWED_FLYWHEEL_TARGETS),
        "regression_test": res_reg,
        "binary_classification_test": res_bin,
    }
    (Path(__file__).resolve().parent / "ns5_rust_fitness_receipt.json").write_text(
        json.dumps(report, indent=2)
    )
    print(json.dumps(report, indent=2))
    return report


if __name__ == "__main__":
    run_self_test()
